'use strict';
// Creator CRM is additive: all historical coupons, paid orders, TikTok checks,
// and expense-backed payouts remain the source of truth. No PII is returned to creators.
function createAdminCreatorCrm(database) {
  const pg=database.backend==='postgres';
  let ready;
  async function q(sql,args=[],tx=database){
    if(pg){let n=0;const r=await tx._query(sql.replace(/\?/g,()=>'$'+(++n)),args);return r.rows||[];}
    const stmt=tx.db.prepare(sql);
    return /^\s*(SELECT|WITH)\b/i.test(sql)||/\bRETURNING\b/i.test(sql)?stmt.all(...args):stmt.run(...args);
  }
  const fail=(message,status=400)=>{const e=new Error(message);e.status=status;throw e;};
  function str(value,max=500){return String(value==null?'':value).trim().slice(0,max);}
  function ensureId(value){const n=Number(value);if(!Number.isSafeInteger(n)||n<1)fail('invalid_id');return n;}
  function isoDate(value){const t=String(value||'');if(!/^\d{4}-\d{2}-\d{2}$/.test(t))return null;const date=new Date(t+'T12:00:00Z');return Number.isFinite(date.getTime())&&date.toISOString().slice(0,10)===t?t:null;}
  async function init(){
    if(!ready)ready=(async()=>{
      const id=pg?'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY':'INTEGER PRIMARY KEY AUTOINCREMENT';
      const sql=[
        `CREATE TABLE IF NOT EXISTS admin_creator_profiles(id ${id},user_id INTEGER UNIQUE REFERENCES users(id) ON DELETE SET NULL,name TEXT NOT NULL,email TEXT NOT NULL DEFAULT '',status TEXT NOT NULL DEFAULT 'candidate' CHECK(status IN ('candidate','active','paused','ended')),notes TEXT NOT NULL DEFAULT '',created_at BIGINT NOT NULL,updated_at BIGINT NOT NULL)`,
        `CREATE INDEX IF NOT EXISTS idx_admin_creator_profiles_status ON admin_creator_profiles(status,updated_at DESC)`,
        `CREATE TABLE IF NOT EXISTS admin_creator_contacts(id ${id},profile_id INTEGER NOT NULL REFERENCES admin_creator_profiles(id) ON DELETE CASCADE,channel TEXT NOT NULL,contacted_at BIGINT NOT NULL,replied_at BIGINT,reply_status TEXT NOT NULL DEFAULT 'pending',note TEXT NOT NULL DEFAULT '',actor_id INTEGER,created_at BIGINT NOT NULL)`,
        `CREATE INDEX IF NOT EXISTS idx_admin_creator_contacts_profile ON admin_creator_contacts(profile_id,contacted_at DESC)`,
        `CREATE TABLE IF NOT EXISTS admin_creator_documents(id ${id},profile_id INTEGER NOT NULL REFERENCES admin_creator_profiles(id) ON DELETE CASCADE,name TEXT NOT NULL,mime TEXT NOT NULL,content_base64 TEXT NOT NULL,byte_size INTEGER NOT NULL,actor_id INTEGER,created_at BIGINT NOT NULL)`,
        `CREATE TABLE IF NOT EXISTS admin_creator_campaign_costs(id ${id},profile_id INTEGER NOT NULL REFERENCES admin_creator_profiles(id) ON DELETE CASCADE,label TEXT NOT NULL,amount_agorot BIGINT NOT NULL CHECK(amount_agorot>0),spent_on TEXT NOT NULL,actor_id INTEGER,created_at BIGINT NOT NULL)`,
        `CREATE TABLE IF NOT EXISTS admin_creator_payment_references(payment_id INTEGER PRIMARY KEY REFERENCES admin_creator_payments(id) ON DELETE CASCADE,reference TEXT NOT NULL DEFAULT '',actor_id INTEGER,updated_at BIGINT NOT NULL)`,
        `CREATE TABLE IF NOT EXISTS admin_creator_crm_history(id ${id},profile_id INTEGER NOT NULL REFERENCES admin_creator_profiles(id) ON DELETE CASCADE,actor_id INTEGER,actor_name TEXT NOT NULL,action TEXT NOT NULL,details TEXT NOT NULL DEFAULT '',created_at BIGINT NOT NULL)`
      ];
      for(const line of sql)await q(line);
      await syncCreators();
    })().catch(e=>{ready=null;throw e;});
    return ready;
  }
  async function syncCreators(){
    // A prospect added before registration becomes linked to the existing
    // website user after the creator code is granted; do not duplicate them.
    await q(`UPDATE admin_creator_profiles SET user_id=(
      SELECT u.id FROM users u JOIN creator_codes c ON c.user_id=u.id
      WHERE LOWER(u.email)=LOWER(admin_creator_profiles.email)
      ORDER BY c.created_at DESC LIMIT 1)
      WHERE user_id IS NULL AND email<>'' AND EXISTS(
      SELECT 1 FROM users u JOIN creator_codes c ON c.user_id=u.id
      WHERE LOWER(u.email)=LOWER(admin_creator_profiles.email))`);
    // Historical codes are not modified; each creator gets one CRM profile.
    await q(`INSERT INTO admin_creator_profiles(user_id,name,email,status,notes,created_at,updated_at)
      SELECT u.id,u.name,u.email,CASE WHEN u.role='contentcreator' AND u.is_blocked=0
        AND EXISTS(SELECT 1 FROM creator_codes c WHERE c.user_id=u.id AND c.active=1) THEN 'active' ELSE 'ended' END,
        '',MIN(c.created_at),? FROM creator_codes c JOIN users u ON u.id=c.user_id
      WHERE NOT EXISTS(SELECT 1 FROM admin_creator_profiles p WHERE p.user_id=u.id)
      GROUP BY u.id,u.name,u.email,u.role,u.is_blocked`,[Date.now()]);
  }
  async function history(profile,actor,action,detail=''){
    await q('INSERT INTO admin_creator_crm_history(profile_id,actor_id,actor_name,action,details,created_at) VALUES(?,?,?,?,?,?)',[
      profile,actor?.id||null,str(actor?.name||actor?.email||'מנהל',120),action,str(detail,300),Date.now()]);
  }
  async function read(id){await init();const profile=(await q('SELECT * FROM admin_creator_profiles WHERE id=?',[ensureId(id)]))[0];if(!profile)fail('creator_profile_not_found',404);return profile;}
  async function profileForUser(userId){await init();const p=(await q('SELECT id FROM admin_creator_profiles WHERE user_id=?',[ensureId(userId)]))[0];return p?.id||null;}
  async function touchUser(userId,status='active'){
    await init();await syncCreators();const p=await profileForUser(userId);
    if(p){await q('UPDATE admin_creator_profiles SET status=?,updated_at=? WHERE id=?',[status,Date.now(),p]);return p;}
    return null;
  }
  async function createProfile(body,actor){await init();
    const name=str(body.name,120),email=str(body.email,254).toLowerCase();
    if(name.length<2||email && !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email))fail('invalid_creator_profile');
    if(email){const existing=await q('SELECT id FROM admin_creator_profiles WHERE LOWER(email)=? LIMIT 1',[email]);if(existing[0])fail('creator_profile_exists',409);}
    // Candidates can be added before they have a registered website account.
    const now=Date.now();
    const r=await q('INSERT INTO admin_creator_profiles(name,email,status,notes,created_at,updated_at) VALUES(?,?,?,?,?,?) RETURNING id',[name,email,'candidate',str(body.notes,3000),now,now]);
    const id=Number(r[0].id);await history(id,actor,'יצירת מועמד');return {id};
  }
  async function updateProfile(id,body,actor){const current=await read(id),status=str(body.status,20)||current.status;
    if(!['candidate','active','paused','ended'].includes(status))fail('invalid_creator_status');
    const name=str(body.name,120)||current.name,notes=body.notes===undefined?current.notes:str(body.notes,3000);
    const email=body.email===undefined?current.email:str(body.email,254).toLowerCase();
    if(email&&!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email))fail('invalid_email');
    if(status==='active'&&!current.user_id)fail('creator_account_required',409);
    if(status==='active'){
      const user=(await q('SELECT role,is_blocked FROM users WHERE id=?',[current.user_id]))[0];
      if(user?.role!=='contentcreator'||Number(user.is_blocked)!==0)fail('creator_account_required',409);
      const code=(await q('SELECT code FROM creator_codes WHERE user_id=? ORDER BY active DESC,created_at DESC LIMIT 1',[current.user_id]))[0];
      if(!code)fail('creator_code_required',409);
    }
    await database.transaction(async tx=>{
      await q('UPDATE admin_creator_profiles SET name=?,email=?,notes=?,status=?,updated_at=? WHERE id=?',[name,email,notes,status,Date.now(),current.id],tx);
      // Pausing or ending a creator disables redemption of that creator's codes.
      // Reactivation restores only the most recently created code, never old codes.
      if(current.user_id && status!==current.status){
        await q('UPDATE creator_codes SET active=0 WHERE user_id=?',[current.user_id],tx);
        if(status==='active')await q('UPDATE creator_codes SET active=1 WHERE code=(SELECT code FROM creator_codes WHERE user_id=? ORDER BY created_at DESC,code DESC LIMIT 1)',[current.user_id],tx);
        if(status==='paused'||status==='ended'){
          await q("UPDATE creator_videos SET status='paused' WHERE user_id=? AND status='active'",[current.user_id],tx);
        }
      }
    });
    await history(current.id,actor,'עדכון פרופיל',`${current.status} → ${status}`);
    return {id:current.id,status};
  }
  async function contact(id,body,actor){await read(id);
    const channel=str(body.channel,50)||'אחר',replyStatus=str(body.replyStatus,25)||'pending';
    if(!['pending','responded','no_response','declined','agreed'].includes(replyStatus))fail('invalid_reply_status');
    if(!isoDate(body.contactedAt)||(body.repliedAt&&!isoDate(body.repliedAt)))fail('invalid_contact_dates');
    const contactedAt=Date.parse(String(body.contactedAt)+'T12:00:00Z');
    const repliedAt=body.repliedAt?Date.parse(String(body.repliedAt)+'T12:00:00Z'):null;
    if(repliedAt!==null&&repliedAt<contactedAt)fail('invalid_contact_dates');
    await q('INSERT INTO admin_creator_contacts(profile_id,channel,contacted_at,replied_at,reply_status,note,actor_id,created_at) VALUES(?,?,?,?,?,?,?,?)',[id,channel,contactedAt,repliedAt,replyStatus,str(body.note,1500),actor?.id||null,Date.now()]);
    await history(id,actor,'תיעוד פנייה',channel);return {ok:true};
  }
  async function updateContact(profileId,contactId,body,actor){
    const profile=await read(profileId),cid=ensureId(contactId);
    const old=(await q('SELECT id,contacted_at,channel,note FROM admin_creator_contacts WHERE profile_id=? AND id=?',[profile.id,cid]))[0];
    if(!old)fail('creator_contact_not_found',404);
    const status=str(body.replyStatus,25),date=body.repliedAt?isoDate(body.repliedAt):null;
    if(!['pending','responded','no_response','declined','agreed'].includes(status)||body.repliedAt&&!date)fail('invalid_reply_status');
    const at=date?Date.parse(date+'T12:00:00Z'):null;
    if(at!==null&&at<Number(old.contacted_at))fail('invalid_contact_dates');
    await q('UPDATE admin_creator_contacts SET replied_at=?,reply_status=?,note=? WHERE id=? AND profile_id=?',[
      at,status,body.note===undefined?old.note:str(body.note,1500),cid,profile.id]);
    await history(profile.id,actor,'עדכון תגובת יוצר',String(cid));return {ok:true};
  }
  async function addCost(id,body,actor){await read(id);
    const amount=Number(body.amountAgorot),spent=isoDate(body.spentOn),label=str(body.label,150);
    if(!Number.isSafeInteger(amount)||amount<1||amount>10000000000||!spent||!label)fail('invalid_campaign_cost');
    await q('INSERT INTO admin_creator_campaign_costs(profile_id,label,amount_agorot,spent_on,actor_id,created_at) VALUES(?,?,?,?,?,?)',[id,label,amount,spent,actor?.id||null,Date.now()]);
    await history(id,actor,'רישום עלות קמפיין',`${label}: ${amount}`);return {ok:true};
  }
  async function deleteCost(profileId,costId,actor){await read(profileId);
    const result=await q('DELETE FROM admin_creator_campaign_costs WHERE id=? AND profile_id=? RETURNING id',[ensureId(costId),ensureId(profileId)]);
    if(!result.length)fail('campaign_cost_not_found',404);
    await history(profileId,actor,'מחיקת עלות קמפיין',String(costId));return {ok:true};
  }
  async function addDocument(id,body,actor){await read(id);
    const name=str(body.name,160).replace(/[\\/<>\r\n]/g,'_');
    const mime=str(body.mime,90);const allowed=['application/pdf','image/png','image/jpeg','image/webp'];
    if(!name||!allowed.includes(mime)||typeof body.base64!=='string'||body.base64.length>3000000||!/^([A-Za-z0-9+/]{4})*([A-Za-z0-9+/]{2}==|[A-Za-z0-9+/]{3}=)?$/.test(body.base64))fail('invalid_document');
    const data=Buffer.from(body.base64,'base64');
    if(!data.length||data.length>2*1024*1024)fail('document_too_large');
    const pdf=data.subarray(0,5).toString()==='%PDF-';
    const png=data.subarray(0,8).equals(Buffer.from([137,80,78,71,13,10,26,10]));
    const jpg=data[0]===255&&data[1]===216&&data[2]===255;
    const webp=data.subarray(0,4).toString()==='RIFF'&&data.subarray(8,12).toString()==='WEBP';
    if(!({ 'application/pdf':pdf, 'image/png':png,'image/jpeg':jpg,'image/webp':webp })[mime])fail('document_format_mismatch');
    const r=await q('INSERT INTO admin_creator_documents(profile_id,name,mime,content_base64,byte_size,actor_id,created_at) VALUES(?,?,?,?,?,?,?) RETURNING id',[id,name,mime,body.base64,data.length,actor?.id||null,Date.now()]);
    await history(id,actor,'צירוף מסמך',name);return {id:Number(r[0].id)};
  }
  async function document(profileId,docId){await read(profileId);
    const row=(await q('SELECT id,name,mime,content_base64 FROM admin_creator_documents WHERE id=? AND profile_id=?',[ensureId(docId),ensureId(profileId)]))[0];
    if(!row)fail('document_not_found',404);
    return {name:row.name,mime:row.mime,buffer:Buffer.from(row.content_base64,'base64')};
  }
  async function setPaymentReference(profileId,paymentId,ref,actor){const profile=await read(profileId);
    if(!profile.user_id)fail('creator_account_required',409);
    const payment=(await q('SELECT id FROM admin_creator_payments WHERE id=? AND creator_id=?',[ensureId(paymentId),Number(profile.user_id)]))[0];
    if(!payment)fail('creator_payment_not_found',404);
    const reference=str(ref,250);if(!reference)fail('payment_reference_required');
    await q(`INSERT INTO admin_creator_payment_references(payment_id,reference,actor_id,updated_at) VALUES(?,?,?,?)
      ON CONFLICT(payment_id) DO UPDATE SET reference=excluded.reference,actor_id=excluded.actor_id,updated_at=excluded.updated_at`,[payment.id,reference,actor?.id||null,Date.now()]);
    await history(profile.id,actor,'שמירת אסמכתת תשלום',`תשלום ${payment.id}`);return {ok:true};
  }
  async function financials(){await init();
    // Paid orders are attributed by the coupon code, even if the code is now inactive.
    // Commission rate comes from the rate effective at each order's paid_at timestamp.
    const orders=await q(`SELECT c.user_id,COUNT(o.id) AS orders,COALESCE(SUM(o.amount_agorot),0) AS revenue,
      COALESCE(SUM(CAST(ROUND(o.amount_agorot * COALESCE((SELECT h.commission_percent FROM creator_commission_rates h
         WHERE h.code=o.coupon_code AND h.effective_at<=o.paid_at ORDER BY h.effective_at DESC,h.id DESC LIMIT 1),0)/100.0) AS INTEGER)),0) AS commission
      FROM creator_codes c JOIN orders o ON o.coupon_code=c.code AND o.status='paid' GROUP BY c.user_id`);
    const views=await q('SELECT v.user_id,COALESCE(SUM(ch.added_views),0) AS views,COALESCE(SUM(ch.earned_agorot),0) AS earned FROM creator_videos v JOIN creator_video_checks ch ON ch.video_ref=v.id GROUP BY v.user_id');
    const payments=await q('SELECT creator_id AS user_id,COALESCE(SUM(amount_agorot),0) AS paid FROM admin_creator_payments GROUP BY creator_id');
    const costs=await q('SELECT profile_id,COALESCE(SUM(amount_agorot),0) AS cost FROM admin_creator_campaign_costs GROUP BY profile_id');
    // Only manually confirmed, non-cancelled refunds in the existing finance ledger.
    const refunds=await q(`SELECT c.user_id,COALESCE(SUM(r.amount_agorot),0) AS refunded
      FROM creator_codes c JOIN orders o ON o.coupon_code=c.code AND o.status='paid'
      JOIN admin_order_refunds r ON r.order_ref=o.order_ref AND r.status='confirmed' AND r.cancelled_at IS NULL
      GROUP BY c.user_id`).catch(e=>{if(/no such table|does not exist/i.test(e.message))return [];throw e;});
    // Genuine tracked 30-day visit-to-purchase conversions, not TikTok views / sales.
    // Only UTM sessions carrying the actual creator code and paid orders linked
    // to that same visitor or signed-in account qualify for this cohort.
    const since=Date.now()-30*86400000;
    const conversions=await q(`SELECT c.user_id,COUNT(DISTINCT pv.visitor_id) AS visitors,
      COUNT(DISTINCT CASE WHEN EXISTS(SELECT 1 FROM orders o WHERE o.status='paid' AND o.paid_at>=?
      AND o.coupon_code=c.code AND (o.guest_visitor_id=pv.visitor_id OR (pv.user_id IS NOT NULL AND o.user_id=pv.user_id)))
      THEN pv.visitor_id ELSE NULL END) AS buyers
      FROM creator_codes c JOIN visitor_page_views pv ON pv.viewed_at>=? AND
      (UPPER(COALESCE(pv.utm_campaign,''))=UPPER(c.code) OR UPPER(COALESCE(pv.utm_content,''))=UPPER(c.code))
      GROUP BY c.user_id`,[since,since]);
    const by=(rows,key)=>new Map(rows.map(r=>[Number(r[key]),r]));
    return {orders:by(orders,'user_id'),views:by(views,'user_id'),payments:by(payments,'user_id'),costs:by(costs,'profile_id'),refunds:by(refunds,'user_id'),conversions:by(conversions,'user_id')};
  }
  function enrich(p,data){
    const uid=Number(p.user_id),id=Number(p.id);
    const sale=data.orders.get(uid)||{},views=data.views.get(uid)||{},payments=data.payments.get(uid)||{},cost=data.costs.get(id)||{},conv=data.conversions.get(uid)||{},refunds=data.refunds.get(uid)||{};
    const revenue=Number(sale.revenue||0),commission=Number(sale.commission||0),video=Number(views.earned||0),campaign=Number(cost.cost||0),paid=Number(payments.paid||0);
    const totalCost=commission+video+campaign,refunded=Number(refunds.refunded||0),netRevenue=revenue-refunded;
    return {id,name:p.name,email:p.email,status:p.status,userId:p.user_id==null?null:uid,notes:p.notes,updatedAt:Number(p.updated_at),
      orders:Number(sale.orders||0),views:Number(views.views||0),revenueAgorot:revenue,refundsAgorot:refunded,netAttributedRevenueAgorot:netRevenue,commissionAgorot:commission,videoRewardsAgorot:video,
      campaignCostsAgorot:campaign,paidAgorot:paid,dueAgorot:Math.max(0,commission+video-paid),
      attributionMarginAgorot:netRevenue-totalCost,roiPercent:totalCost>0?Math.round((netRevenue-totalCost)/totalCost*10000)/100:null,
      roas:totalCost>0?Math.round(netRevenue/totalCost*100)/100:null,conversionVisitors:Number(conv.visitors||0),conversionBuyers:Number(conv.buyers||0),
      conversionPercent:Number(conv.visitors||0)>0?Math.round(Number(conv.buyers||0)/Number(conv.visitors)*10000)/100:null};
  }
  async function list(){await init();await syncCreators();const rows=await q('SELECT * FROM admin_creator_profiles ORDER BY updated_at DESC,id DESC LIMIT 1000');const data=await financials();return rows.map(x=>enrich(x,data));}
  async function detail(id){const p=await read(id),data=await financials();
    const [contacts,docs,costs,payments,hist,codes,videos,orders]=await Promise.all([
      q('SELECT id,channel,contacted_at,replied_at,reply_status,note,created_at FROM admin_creator_contacts WHERE profile_id=? ORDER BY contacted_at DESC,id DESC LIMIT 100',[p.id]),
      q('SELECT id,name,mime,byte_size,created_at FROM admin_creator_documents WHERE profile_id=? ORDER BY id DESC LIMIT 100',[p.id]),
      q('SELECT id,label,amount_agorot,spent_on FROM admin_creator_campaign_costs WHERE profile_id=? ORDER BY spent_on DESC,id DESC LIMIT 150',[p.id]),
      p.user_id?q('SELECT p.id,p.amount_agorot,p.paid_at,p.note,r.reference FROM admin_creator_payments p LEFT JOIN admin_creator_payment_references r ON r.payment_id=p.id WHERE p.creator_id=? ORDER BY p.paid_at DESC,id DESC LIMIT 150',[p.user_id]):[],
      q('SELECT actor_name,action,details,created_at FROM admin_creator_crm_history WHERE profile_id=? ORDER BY id DESC LIMIT 80',[p.id]),
      p.user_id?q('SELECT code,active,discount_percent,commission_percent,created_at FROM creator_codes WHERE user_id=? ORDER BY created_at DESC',[p.user_id]):[],
      p.user_id?q('SELECT video_url,status,last_views FROM creator_videos WHERE user_id=? ORDER BY submitted_at DESC LIMIT 60',[p.user_id]):[],
      p.user_id?q("SELECT o.order_ref,o.amount_agorot,o.paid_at,o.coupon_code FROM orders o JOIN creator_codes c ON c.code=o.coupon_code WHERE c.user_id=? AND o.status='paid' ORDER BY o.paid_at DESC,o.id DESC LIMIT 100",[p.user_id]):[]
    ]);
    return {profile:enrich(p,data),contacts,documents:docs,campaignCosts:costs,payments,history:hist,codes,videos,orders};
  }
  return {init,list,detail,read,createProfile,updateProfile,contact,updateContact,addCost,deleteCost,addDocument,document,setPaymentReference,touchUser,profileForUser};
}
module.exports={createAdminCreatorCrm};
