'use strict';

// Dashboard persistence, creator liability and analytics share the existing
// PostgreSQL/SQLite store. Financial amounts are always integer agorot.
const TZ = 'Asia/Jerusalem';
const dayFmt = new Intl.DateTimeFormat('en-CA', {timeZone:TZ,year:'numeric',month:'2-digit',day:'2-digit'});
function dayKey(ms) {
  const p={};for(const part of dayFmt.formatToParts(new Date(ms)))if(part.type!=='literal')p[part.type]=part.value;
  return `${p.year}-${p.month}-${p.day}`;
}
function validateDate(value) {
  if(typeof value!=='string'|| !/^\d{4}-\d{2}-\d{2}$/.test(value))return false;
  const ms=Date.parse(value+'T12:00:00Z');return Number.isFinite(ms)&&new Date(ms).toISOString().slice(0,10)===value;
}
function createAdminDashboard(database,creatorProgram) {
  const pg=database.backend==='postgres';
  let ready;
  async function query(statement,values=[]) {
    if(pg){let n=0;const r=await database._query(statement.replace(/\?/g,()=>'\u0024'+(++n)),values);return r.rows||[];}
    const stmt=database.db.prepare(statement);
    return /^\s*SELECT\b/i.test(statement) ? stmt.all(...values) : stmt.run(...values);
  }
  async function init() {
    if(!ready)ready=(async()=>{
      const id=pg?'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY':'INTEGER PRIMARY KEY AUTOINCREMENT';
      const statements=[
        `CREATE TABLE IF NOT EXISTS admin_sales_targets (month_key TEXT PRIMARY KEY, goal_agorot BIGINT NOT NULL CHECK(goal_agorot>=0), updated_at BIGINT NOT NULL, updated_by INTEGER REFERENCES users(id))`,
        `CREATE TABLE IF NOT EXISTS admin_activity_log (id ${id}, actor_id INTEGER REFERENCES users(id) ON DELETE SET NULL, actor_name TEXT NOT NULL, area TEXT NOT NULL, action TEXT NOT NULL, subject TEXT NOT NULL, created_at BIGINT NOT NULL)`,
        `CREATE INDEX IF NOT EXISTS idx_admin_activity_time ON admin_activity_log(created_at DESC,id DESC)`,
        `CREATE TABLE IF NOT EXISTS admin_creator_payments (id ${id}, creator_id INTEGER NOT NULL REFERENCES users(id), amount_agorot BIGINT NOT NULL CHECK(amount_agorot>0), note TEXT NOT NULL DEFAULT '', actor_id INTEGER REFERENCES users(id) ON DELETE SET NULL, paid_at BIGINT NOT NULL, request_id TEXT NOT NULL UNIQUE)`,
        `CREATE INDEX IF NOT EXISTS idx_admin_creator_payments_creator ON admin_creator_payments(creator_id,paid_at DESC)`
      ];
      for(const sql of statements)await query(sql);
    })().catch(e=>{ready=null;throw e;});
    return ready;
  }
  async function log(actor,area,action,subject){
    await init();
    await query('INSERT INTO admin_activity_log(actor_id,actor_name,area,action,subject,created_at) VALUES(?,?,?,?,?,?)',[
      Number(actor.id),String(actor.name||actor.email||'אדמין').slice(0,120),area,action,String(subject||'').slice(0,180),Date.now()]);
  }
  async function activity(permissions){
    await init();
    const areas=permissions.includes('all')?['products','orders','creators','dashboard']:permissions;
    if(!areas.length)return [];
    const rows=await query(`SELECT id,actor_name,area,action,subject,created_at FROM admin_activity_log WHERE area IN (${areas.map(()=>'?').join(',')}) ORDER BY created_at DESC,id DESC LIMIT 35`,areas);
    return rows.map(r=>({id:Number(r.id),actor:r.actor_name,area:r.area,action:r.action,subject:r.subject,at:Number(r.created_at)}));
  }
  async function setGoal(month,amount,actor){
    await init();
    if(!/^\d{4}-(0[1-9]|1[0-2])$/.test(month)||!Number.isSafeInteger(amount)||amount<0||amount>100000000000)
      throw Object.assign(new Error('invalid_goal'),{status:400});
    await query(`INSERT INTO admin_sales_targets(month_key,goal_agorot,updated_at,updated_by) VALUES(?,?,?,?)
      ON CONFLICT(month_key) DO UPDATE SET goal_agorot=excluded.goal_agorot,updated_at=excluded.updated_at,updated_by=excluded.updated_by`,[month,amount,Date.now(),actor.id]);
    await log(actor,'dashboard','עדכון יעד מכירות',month);
    return {month,goalAgorot:amount};
  }
  async function creatorLiabilities(){
    await init();
    const creators=await creatorProgram.listCreators();
    const [videoResult,payments]=await Promise.all([
      query(`SELECT v.user_id,COALESCE(SUM(ch.earned_agorot),0) AS earned FROM creator_videos v LEFT JOIN creator_video_checks ch ON ch.video_ref=v.id GROUP BY v.user_id`)
        .then(rows=>({rows,available:true})).catch(error=>{
          if(/(no such table|does not exist)/i.test(error.message))return {rows:[],available:false};
          throw error;
        }),
      query('SELECT creator_id,COALESCE(SUM(amount_agorot),0) AS paid FROM admin_creator_payments GROUP BY creator_id')
    ]);
    const videos=videoResult.rows;
    const videoMap=new Map(videos.map(r=>[Number(r.user_id),Number(r.earned)||0]));
    const paidMap=new Map(payments.map(r=>[Number(r.creator_id),Number(r.paid)||0]));
    const items=creators.map(c=>{
      const commissionAgorot=Math.round(Number(c.commissionAgorot)||0);
      const videoAgorot=Math.round(videoMap.get(Number(c.id))||0);
      const paidAgorot=Math.round(paidMap.get(Number(c.id))||0);
      return {id:c.id,name:c.name,code:c.code||'',commissionAgorot,videoAgorot,paidAgorot,
        dueAgorot:Math.max(0,commissionAgorot+videoAgorot-paidAgorot)};
    });
    return {items,videoRewardsAvailable:videoResult.available,totalDueAgorot:items.reduce((s,c)=>s+c.dueAgorot,0)};
  }
  async function payCreator(creatorId,amount,requestId,note,actor,reference=''){
    await init();
    if(!Number.isSafeInteger(creatorId)||creatorId<=0||!Number.isSafeInteger(amount)||amount<=0||amount>100000000000 ||
      typeof requestId!=='string'||! /^[a-f\d-]{36}$/i.test(requestId)||typeof note!=='string'||note.length>200||typeof reference!=='string'||reference.length>250)
      throw Object.assign(new Error('invalid_payment'),{status:400});
    const liability=(await creatorLiabilities()).items.find(x=>Number(x.id)===creatorId);
    if(!liability)throw Object.assign(new Error('payment_exceeds_balance'),{status:409});
    // All deductions are committed atomically. Serialize payout changes per creator
    // across multiple Render workers (PG advisory transaction lock / SQLite BEGIN IMMEDIATE).
    const recorded=await database.transaction(async tx=>{
      if(pg)await tx._query('SELECT pg_advisory_xact_lock($1)',[creatorId]);
      const find=async(statement,params=[])=>{
        if(pg){let i=0;return (await tx._query(statement.replace(/\?/g,()=>'$'+(++i)),params)).rows||[];}
        return tx.db.prepare(statement).all(...params);
      };
      const already=await find('SELECT id,creator_id,amount_agorot FROM admin_creator_payments WHERE request_id=?',[requestId]);
      if(already.length){if(Number(already[0].creator_id)!==creatorId||Number(already[0].amount_agorot)!==amount)throw Object.assign(new Error('payment_key_conflict'),{status:409});return {duplicate:true};}
      // Recheck payments under the creator's exclusive write lock; a concurrent
      // admin request must not be able to record the same balance twice.
      const sums=await find('SELECT COALESCE(SUM(amount_agorot),0) AS paid_agorot FROM admin_creator_payments WHERE creator_id=?',[creatorId]);
      const due=Math.max(0,liability.commissionAgorot+liability.videoAgorot-Number(sums[0].paid_agorot||0));
      if(amount>due)throw Object.assign(new Error('payment_exceeds_balance'),{status:409});
      // The creator payout and its expense must either both exist or neither exist.
      // Reuse the payout request ID as the expense ledger's idempotency key.
      const paidAt=Date.now();
      if(pg)await tx._query('INSERT INTO admin_creator_payments(creator_id,amount_agorot,note,actor_id,paid_at,request_id) VALUES($1,$2,$3,$4,$5,$6)',
        [creatorId,amount,note.trim(),actor.id,paidAt,requestId]);
      else tx.db.prepare('INSERT INTO admin_creator_payments(creator_id,amount_agorot,note,actor_id,paid_at,request_id) VALUES(?,?,?,?,?,?)')
        .run(creatorId,amount,note.trim(),actor.id,paidAt,requestId);
      if(reference.trim()){
        const existingPayment=await find('SELECT id FROM admin_creator_payments WHERE request_id=?',[requestId]);
        if(pg)await tx._query('INSERT INTO admin_creator_payment_references(payment_id,reference,actor_id,updated_at) VALUES($1,$2,$3,$4)',[existingPayment[0].id,reference.trim(),actor.id,paidAt]);
        else tx.db.prepare('INSERT INTO admin_creator_payment_references(payment_id,reference,actor_id,updated_at) VALUES(?,?,?,?)').run(existingPayment[0].id,reference.trim(),actor.id,paidAt);
      }
      const creatorName=String(liability.name||liability.code||'יוצר תוכן').trim().slice(0,140);
      const detail=note.trim();
      const description=`תשלום ליוצר תוכן - ${creatorName}${detail ? ' - '+detail : ''}`.slice(0,300);
      await tx.createAdminExpense({
        description,category:'יוצרי תוכן',amountAgorot:amount,
        expenseDate:dayKey(paidAt),employeeUserId:Number(actor.id),
        employeeName:String(actor.name||actor.email||'אדמין').slice(0,150),
        requestId,createdAt:paidAt,
        // The payout action does not identify which business partner paid;
        // do not silently allocate the cost to Maor or Gal.
        maorAgorot:null,galAgorot:null
      });
      return {duplicate:false,name:liability.name};
    });
    if(!recorded.duplicate){
      try{await log(actor,'creators','רישום תשלום ליוצר',`${recorded.name} · ${(amount/100).toFixed(2)} ₪`);}
      catch(error){console.error('Creator payment activity log failed:',error.message);}
    }
    return {recorded:true,duplicate:recorded.duplicate};
  }
  async function insights({aFrom,aTo,bFrom,bTo,withCreators=false,permissions=[]}={}){
    await init();
    const today=dayKey(Date.now()),month=today.slice(0,7);
    const first=month+'-01', year=Number(month.slice(0,4)),monthNum=Number(month.slice(5,7));
    const daysInMonth=new Date(Date.UTC(year,monthNum,0)).getUTCDate();
    const elapsed=Number(today.slice(8));
    const selected=[aFrom,aTo,bFrom,bTo];const any=selected.some(Boolean);
    if(any && (!selected.every(validateDate)||aFrom>aTo||bFrom>bTo))
      throw Object.assign(new Error('invalid_comparison_dates'),{status:400});
    // Do not accidentally fetch unlimited historical purchases if no comparison is requested.
    const sinceDate=any ? [first,aFrom,bFrom].sort()[0] : first;
    const rows=await database.listOrdersForAnalytics('paid',Date.parse(sinceDate+'T00:00:00Z')-86400000);
    const amounts=new Map(),counts=new Map(),units=new Map();
    let monthlyAgorot=0;
    for(const o of rows){
      const k=dayKey(Number(o.paid_at||o.created_at));
      const amount=Math.round(Number(o.amount_agorot)||0);
      amounts.set(k,(amounts.get(k)||0)+amount);counts.set(k,(counts.get(k)||0)+1);
      let qty=0;try{for(const item of JSON.parse(o.items_json||'[]'))qty+=Math.max(1,Number(item.qty||1));}catch(_){}
      units.set(k,(units.get(k)||0)+qty);
      if(k>=first && k<=today)monthlyAgorot+=amount;
    }
    const dateKeys=[];for(let d=1;d<=elapsed;d++)dateKeys.push(month+'-'+String(d).padStart(2,'0'));
    const daily=dateKeys.map(k=>amounts.get(k)||0);const average=monthlyAgorot/elapsed;
    const variance=elapsed>1?daily.reduce((s,v)=>s+(v-average)**2,0)/(elapsed-1):0;
    const futureDays=daysInMonth-elapsed;
    const projected=Math.round(monthlyAgorot+average*futureDays);
    // Predictive (not merely mean-estimation) normal approximation for the future sum.
    // Includes daily variability as well as error in the estimated mean.
    const margin=elapsed>=7 && monthlyAgorot>0 ? Math.round(1.96*Math.sqrt(variance*(futureDays+futureDays*futureDays/elapsed))):null;
    const goalRows=await query('SELECT goal_agorot FROM admin_sales_targets WHERE month_key=?',[month]);
    const goal=goalRows.length?Number(goalRows[0].goal_agorot)||0:0;
    function totals(from,to){
      let revenueAgorot=0,orderCount=0,unitsSold=0,days=0;
      for(let t=Date.parse(from+'T00:00:00Z');t<=Date.parse(to+'T00:00:00Z');t+=86400000){
        const key=new Date(t).toISOString().slice(0,10);revenueAgorot+=amounts.get(key)||0;orderCount+=counts.get(key)||0;unitsSold+=units.get(key)||0;days++;
        if(days>3660)throw Object.assign(new Error('comparison_too_long'),{status:400});
      }
      return {from,to,days,revenueAgorot,orderCount,unitsSold,averageOrderAgorot:orderCount?Math.round(revenueAgorot/orderCount):0};
    }
    const comparison=any?{a:totals(aFrom,aTo),b:totals(bFrom,bTo)}:null;
    const areas=permissions.includes('all')?['products','orders','creators','dashboard']:permissions;
    const [activities,creators]=await Promise.all([activity(areas),withCreators?creatorLiabilities():Promise.resolve(null)]);
    return {month,goalAgorot:goal,monthlyRevenueAgorot:monthlyAgorot,progressPercent:goal?Math.min(100,monthlyAgorot/goal*100):0,
      forecast:{predictedAgorot:projected,lowerAgorot:margin===null?null:Math.max(0,projected-margin),upperAgorot:margin===null?null:projected+margin,elapsedDays:elapsed,totalDays:daysInMonth,sampleDays:elapsed,daysRemaining:futureDays,method:'calendar_daily_mean_normal_95'},
      comparison,activities,creators};
  }
  return {init,log,activity,setGoal,payCreator,creatorLiabilities,insights};
}
module.exports={createAdminDashboard,dayKey,validateDate};
