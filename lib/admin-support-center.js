'use strict';

// Customer-service case management, stored beside existing orders/users.
// Neither a WhatsApp link nor a mailto link counts as a sent message until an
// employee explicitly records the response.
const STATUSES = ['open','in_progress','waiting','closed'];
const REASONS = ['shipping','damaged','size','cancellation','warranty','billing','other'];
const REPLACEMENT_STATES = ['requested','approved','preparing','shipped','delivered','rejected'];
const CHANNELS = ['whatsapp','email'];
const DEFAULT_REMINDER_HOURS = 24;
function fail(message,status=400){const e=new Error(message);e.status=status;throw e;}
function clipped(v,max=500){return String(v==null?'':v).trim().slice(0,max);}
function required(v,max=200){const s=clipped(v,max);if(!s)fail('missing_required_field');return s;}
function validInt(v,allowNull=true){if((v===null||v===undefined||v==='')&&allowNull)return null;const x=Number(v);if(!Number.isSafeInteger(x)||x<1)fail('invalid_id');return x;}
function oneOf(value,values){if(!values.includes(value))fail('invalid_value');return value;}
function createSupportCenter(database,{sendEmail,isEmailConfigured,ownerEmail,staffCanView=async()=>true}){
  const pg=database.backend==='postgres';let ready;
  async function execute(sql,params=[]){
    if(pg){let i=0;return (await database._query(sql.replace(/\?/g,()=>'\$'+(++i)),params)).rows||[];}
    const stmt=database.db.prepare(sql);
    return /^\s*(?:SELECT|WITH)/i.test(sql)?stmt.all(...params):stmt.run(...params);
  }
  async function init(){if(ready)return ready;
    ready=(async()=>{
      const id=pg?'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY':'INTEGER PRIMARY KEY AUTOINCREMENT';
      for(const sql of [
        `CREATE TABLE IF NOT EXISTS support_tickets (
          id ${id},subject TEXT NOT NULL, reason TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'open',
          customer_id INTEGER REFERENCES users(id) ON DELETE SET NULL, order_ref TEXT,
          customer_name TEXT, customer_email TEXT, customer_phone TEXT,
          assignee_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
          reminder_hours INTEGER NOT NULL DEFAULT 24,
          opened_at BIGINT NOT NULL, updated_at BIGINT NOT NULL, closed_at BIGINT,
          last_customer_at BIGINT NOT NULL, last_staff_at BIGINT, first_response_at BIGINT,
          reminded_for_at BIGINT, created_by_id INTEGER, origin_request_ref TEXT UNIQUE)`,
        `CREATE INDEX IF NOT EXISTS idx_support_tickets_status ON support_tickets(status,updated_at DESC)`,
        `CREATE INDEX IF NOT EXISTS idx_support_tickets_customer ON support_tickets(customer_id,opened_at DESC)`,
        `CREATE INDEX IF NOT EXISTS idx_support_tickets_order ON support_tickets(order_ref)`,
        `CREATE TABLE IF NOT EXISTS support_messages (
          id ${id},ticket_id BIGINT NOT NULL REFERENCES support_tickets(id) ON DELETE CASCADE,
          kind TEXT NOT NULL,channel TEXT NOT NULL DEFAULT 'internal',body TEXT NOT NULL,
          actor_id INTEGER,actor_name TEXT NOT NULL,created_at BIGINT NOT NULL)`,
        `CREATE INDEX IF NOT EXISTS idx_support_messages_ticket ON support_messages(ticket_id,created_at DESC)`,
        `CREATE TABLE IF NOT EXISTS support_history (
          id ${id},ticket_id BIGINT NOT NULL REFERENCES support_tickets(id) ON DELETE CASCADE,
          actor_id INTEGER,actor_name TEXT NOT NULL,action TEXT NOT NULL,detail TEXT NOT NULL,created_at BIGINT NOT NULL)`,
        `CREATE TABLE IF NOT EXISTS support_templates (
          id ${id}, title TEXT NOT NULL, channel TEXT NOT NULL,body TEXT NOT NULL,
          created_by_id INTEGER,created_at BIGINT NOT NULL,updated_at BIGINT NOT NULL)`,
        `CREATE TABLE IF NOT EXISTS support_replacements (
          ticket_id BIGINT PRIMARY KEY REFERENCES support_tickets(id) ON DELETE CASCADE,
          product_name TEXT NOT NULL,quantity INTEGER NOT NULL DEFAULT 1,status TEXT NOT NULL,
          tracking_number TEXT,notes TEXT,updated_at BIGINT NOT NULL,updated_by INTEGER)`
      ]){if(pg)await database._query(sql);else database.db.exec(sql);}
      const n=await execute('SELECT COUNT(*) AS count FROM support_templates');
      if(Number(n[0].count)===0){const now=Date.now();
        for(const [title,channel,body] of [
          ['עדכון משלוח','whatsapp','שלום {name}, רצינו לעדכן שבדיקת המשלוח של הזמנה {order} בטיפול. נחזור אליך בהקדם.'],
          ['מוצר פגום','email','שלום {name}, קיבלנו את הפנייה לגבי הזמנה {order}. אנו בודקים את פרטי המוצר ונעדכן לגבי האחריות או ההחלפה.'],
          ['בדיקת מידה','whatsapp','שלום {name}, קיבלנו את פנייתך לגבי המידה בהזמנה {order}. נעזור למצוא פתרון מתאים.']
        ])await execute('INSERT INTO support_templates(title,channel,body,created_by_id,created_at,updated_at) VALUES(?,?,?,?,?,?)',[title,channel,body,null,now,now]);
      }
    })().catch(e=>{ready=null;throw e;});return ready;
  }
  async function syncLegacy(){
    await init();
    // Existing cancellation / return requests remain in their original table.
    // A linked CRM entry is created once; imports never edit the original.
    await execute(`INSERT INTO support_tickets
      (subject,reason,status,customer_id,order_ref,customer_name,customer_email,customer_phone,assignee_id,reminder_hours,opened_at,updated_at,closed_at,last_customer_at,last_staff_at,first_response_at,reminded_for_at,created_by_id,origin_request_ref)
      SELECT 'בקשת '||CASE WHEN cr.request_type='cancel' THEN 'ביטול' ELSE 'החזרה' END||' · '||cr.request_ref,
        CASE WHEN cr.request_type='cancel' THEN 'cancellation' ELSE 'damaged' END,
        CASE WHEN cr.status IN ('completed','declined') THEN 'closed' WHEN cr.status='reviewing' THEN 'in_progress' ELSE 'open' END,
        cr.user_id,cr.order_ref,cr.name,cr.email,cr.phone,NULL,24,cr.created_at,cr.updated_at,
        CASE WHEN cr.status IN ('completed','declined') THEN cr.updated_at ELSE NULL END,
        cr.created_at,NULL,NULL,cr.created_at,NULL,cr.request_ref
      FROM cancellation_requests cr WHERE NOT EXISTS
        (SELECT 1 FROM support_tickets st WHERE st.origin_request_ref=cr.request_ref)
      ON CONFLICT(origin_request_ref) DO NOTHING`);
    await execute(`INSERT INTO support_messages(ticket_id,kind,channel,body,actor_id,actor_name,created_at)
      SELECT t.id,'customer','internal',cr.reason,NULL,'פנייה קיימת במערכת',cr.created_at
      FROM support_tickets t JOIN cancellation_requests cr ON t.origin_request_ref=cr.request_ref
      WHERE cr.reason IS NOT NULL AND cr.reason<>''
        AND NOT EXISTS (SELECT 1 FROM support_messages m WHERE m.ticket_id=t.id)`);
  }
  async function getTicket(id){await init();const rows=await execute(`SELECT t.*,u.name AS assigned_name,c.name AS linked_customer_name
    FROM support_tickets t LEFT JOIN users u ON u.id=t.assignee_id LEFT JOIN users c ON c.id=t.customer_id WHERE t.id=?`,[validInt(id,false)]);
    if(!rows.length)fail('ticket_not_found',404);return rows[0];}
  async function hist(id,actor,action,detail){await execute('INSERT INTO support_history(ticket_id,actor_id,actor_name,action,detail,created_at) VALUES(?,?,?,?,?,?)',
    [id,Number(actor.id),clipped(actor.name||actor.email,100),action,clipped(detail,500),Date.now()]);}
  async function validateLinks(customerId,orderRef){
    let customer=null,order=null;
    if(customerId){const rows=await execute('SELECT id,name,email,phone FROM users WHERE id=? AND role IN (\'customer\',\'contentcreator\')',[customerId]);if(!rows.length)fail('customer_not_found',404);customer=rows[0];}
    if(orderRef){const rows=await execute('SELECT order_ref,user_id,customer_email,customer_phone,customer_json FROM orders WHERE order_ref=?',[orderRef]);if(!rows.length)fail('order_not_found',404);order=rows[0];}
    if(customer && order){const match=Number(order.user_id||0)===customerId || (order.customer_email&&clipped(order.customer_email,255).toLowerCase()===clipped(customer.email,255).toLowerCase());
      if(!match)fail('customer_order_mismatch');}
    return {customer,order};
  }
  async function create(data,actor){await init();const subject=required(data.subject,180),reason=oneOf(data.reason||'other',REASONS);
    const customerId=validInt(data.customerId),orderRef=clipped(data.orderRef,100)||null,assigneeId=validInt(data.assigneeId);
    const {customer,order}=await validateLinks(customerId,orderRef);
    if(assigneeId)await validateAssignee(assigneeId);
    const now=Date.now(),reminderHours=reminderValue(data.reminderHours);
    const customerName=clipped(customer?.name||data.customerName,120),customerEmail=clipped(customer?.email||order?.customer_email||data.customerEmail,255),customerPhone=clipped(customer?.phone||order?.customer_phone||data.customerPhone,70);
    if(!customerId&&!orderRef&&!customerEmail&&!customerPhone)fail('customer_contact_required');
    const values=[subject,reason,'open',customerId,orderRef,customerName,customerEmail,customerPhone,assigneeId,reminderHours,now,now,now,Number(actor.id)];
    let id;
    if(pg){const rows=await execute(`INSERT INTO support_tickets(subject,reason,status,customer_id,order_ref,customer_name,customer_email,customer_phone,assignee_id,reminder_hours,opened_at,updated_at,last_customer_at,created_by_id)
      VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?,?) RETURNING id`,values);id=Number(rows[0].id);}
    else {const out=await execute(`INSERT INTO support_tickets(subject,reason,status,customer_id,order_ref,customer_name,customer_email,customer_phone,assignee_id,reminder_hours,opened_at,updated_at,last_customer_at,created_by_id)
      VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?,?)`,values);id=Number(out.lastInsertRowid);}
    await hist(id,actor,'created','נפתחה פנייה');
    if(clipped(data.body,3000))await message(id,{kind:'customer',body:data.body,channel:'internal'},actor);
    return detail(id);
  }
  function reminderValue(v){if(v==null||v==='')return DEFAULT_REMINDER_HOURS;const n=Number(v);if(!Number.isInteger(n)||n<1||n>720)fail('invalid_reminder_hours');return n;}
  async function validateAssignee(id){const rows=await execute("SELECT id,name,email,role,is_blocked FROM users WHERE id=? AND role IN ('staff','admin')",[id]);if(!rows.length||Number(rows[0].is_blocked))fail('assignee_not_active');if(rows[0].role==='staff'&&!await staffCanView(id))fail('assignee_not_authorized');return rows[0];}
  async function list({status='all',reason='all',assignee='all',search='',limit=30,offset=0}={}){await syncLegacy();
    limit=Math.min(100,Math.max(1,Number(limit)||30));offset=Math.max(0,Number(offset)||0);
    const where=[],params=[];
    if(status!=='all'){oneOf(status,STATUSES);where.push('t.status=?');params.push(status);}
    if(reason!=='all'){oneOf(reason,REASONS);where.push('t.reason=?');params.push(reason);}
    if(assignee==='unassigned')where.push('t.assignee_id IS NULL');else if(assignee!=='all'){where.push('t.assignee_id=?');params.push(validInt(assignee,false));}
    if(search){where.push('(LOWER(t.subject) LIKE ? OR LOWER(COALESCE(t.customer_name,\'\')) LIKE ? OR LOWER(COALESCE(t.customer_email,\'\')) LIKE ? OR LOWER(COALESCE(t.order_ref,\'\')) LIKE ? OR CAST(t.id AS TEXT) LIKE ?)');const q='%'+clipped(search,90).toLowerCase()+'%';params.push(q,q,q,q,q);}
    const clause=where.length?'WHERE '+where.join(' AND '):'';
    const count=await execute('SELECT COUNT(*) AS n FROM support_tickets t '+clause,params);
    const rows=await execute(`SELECT t.*,u.name AS assigned_name FROM support_tickets t LEFT JOIN users u ON u.id=t.assignee_id ${clause} ORDER BY CASE WHEN t.status='closed' THEN 1 ELSE 0 END, t.updated_at DESC,t.id DESC LIMIT ? OFFSET ?`,[...params,limit,offset]);
    return {count:Number(count[0].n),limit,offset,tickets:rows.map(ticketToJson)};
  }
  function ticketToJson(t){return {id:Number(t.id),subject:t.subject,reason:t.reason,status:t.status,customerId:t.customer_id==null?null:Number(t.customer_id),orderRef:t.order_ref,customerName:t.customer_name,customerEmail:t.customer_email,customerPhone:t.customer_phone,assigneeId:t.assignee_id==null?null:Number(t.assignee_id),assigneeName:t.assigned_name||'',openedAt:Number(t.opened_at),updatedAt:Number(t.updated_at),closedAt:t.closed_at==null?null:Number(t.closed_at),lastCustomerAt:Number(t.last_customer_at),lastStaffAt:t.last_staff_at==null?null:Number(t.last_staff_at),firstResponseAt:t.first_response_at==null?null:Number(t.first_response_at),reminderHours:Number(t.reminder_hours),overdue:t.status!=='closed'&&Number(t.last_customer_at)>Number(t.last_staff_at||0)&&Date.now()-Number(t.last_customer_at)>=Number(t.reminder_hours)*3600000};}
  async function detail(id){const t=await getTicket(id),rows=await Promise.all([
    execute('SELECT id,kind,channel,body,actor_name,created_at FROM support_messages WHERE ticket_id=? ORDER BY created_at ASC,id ASC LIMIT 300',[id]),
    execute('SELECT id,action,detail,actor_name,created_at FROM support_history WHERE ticket_id=? ORDER BY created_at DESC,id DESC LIMIT 150',[id]),
    execute('SELECT * FROM support_replacements WHERE ticket_id=?',[id])
  ]);
    return {ticket:ticketToJson(t),messages:rows[0].map(r=>({id:Number(r.id),kind:r.kind,channel:r.channel,body:r.body,actor:r.actor_name,createdAt:Number(r.created_at)})),history:rows[1].map(r=>({id:Number(r.id),action:r.action,detail:r.detail,actor:r.actor_name,createdAt:Number(r.created_at)})),replacement:rows[2][0]||null};}
  async function update(id,data,actor,{mayAssign=false}={}){const before=await getTicket(id);const allowed=['status','reason','subject','reminderHours',...(mayAssign?['assigneeId']:[])];
    if(Object.keys(data).some(k=>!allowed.includes(k)))fail('unsupported_field');
    const changes=[],params=[],descriptions=[];
    for(const [key,col] of [['status','status'],['reason','reason'],['subject','subject'],['reminderHours','reminder_hours'],['assigneeId','assignee_id']]){
      if(!Object.hasOwn(data,key))continue;
      let value=data[key];
      if(key==='status')value=oneOf(value,STATUSES);if(key==='reason')value=oneOf(value,REASONS);
      if(key==='subject')value=required(value,180);if(key==='reminderHours')value=reminderValue(value);
      if(key==='assigneeId'){if(!mayAssign)fail('permission_denied',403);value=validInt(value);if(value)await validateAssignee(value);}
      changes.push(col+'=?');params.push(value);descriptions.push(key+': '+clipped(before[col],80)+' → '+clipped(value,80));
      if(key==='status'){changes.push('closed_at=?');params.push(value==='closed'?Date.now():null);}
    }
    if(!changes.length)return detail(id);
    changes.push('updated_at=?');params.push(Date.now(),id);
    await execute('UPDATE support_tickets SET '+changes.join(',')+' WHERE id=?',params);
    await hist(id,actor,'updated',descriptions.join(' | '));return detail(id);
  }
  async function message(id,data,actor){const ticket=await getTicket(id);
    const kind=oneOf(data.kind,['customer','staff','note']),channel=oneOf(data.channel||'internal',['internal','whatsapp','email','phone']);
    const body=required(data.body,4000),now=Date.now();
    // A staff message is an explicit manual log of a reply, not a promise that
    // opening the external WhatsApp/email composer actually delivered it.
    await execute('INSERT INTO support_messages(ticket_id,kind,channel,body,actor_id,actor_name,created_at) VALUES(?,?,?,?,?,?,?)',
      [ticket.id,kind,channel,body,Number(actor.id),clipped(actor.name||actor.email,100),now]);
    if(kind==='customer')await execute('UPDATE support_tickets SET last_customer_at=?,reminded_for_at=NULL,updated_at=? WHERE id=?',[now,now,id]);
    else if(kind==='staff')await execute('UPDATE support_tickets SET last_staff_at=?,first_response_at=COALESCE(first_response_at,?),updated_at=? WHERE id=?',[now,now,now,id]);
    else await execute('UPDATE support_tickets SET updated_at=? WHERE id=?',[now,id]);
    await hist(id,actor,'message',kind+' · '+channel);return detail(id);
  }
  async function replacement(id,data,actor){const ticket=await getTicket(id);
    if(!ticket.order_ref)fail('replacement_requires_order');
    const status=oneOf(data.status||'requested',REPLACEMENT_STATES),product=required(data.productName,180),qty=Number(data.quantity||1);
    if(!Number.isSafeInteger(qty)||qty<1||qty>100)fail('invalid_quantity');
    const now=Date.now();await execute(`INSERT INTO support_replacements(ticket_id,product_name,quantity,status,tracking_number,notes,updated_at,updated_by)
      VALUES(?,?,?,?,?,?,?,?) ON CONFLICT(ticket_id) DO UPDATE SET product_name=excluded.product_name,quantity=excluded.quantity,status=excluded.status,tracking_number=excluded.tracking_number,notes=excluded.notes,updated_at=excluded.updated_at,updated_by=excluded.updated_by`,
    [id,product,qty,status,clipped(data.trackingNumber,120),clipped(data.notes,1000),now,Number(actor.id)]);
    await hist(id,actor,'replacement',status+' · '+product+' ×'+qty);return detail(id);
  }
  async function templates(){await init();const rows=await execute('SELECT * FROM support_templates ORDER BY updated_at DESC,id DESC LIMIT 200');return rows.map(r=>({id:Number(r.id),title:r.title,channel:r.channel,body:r.body}));}
  async function saveTemplate(data,actor,id=null){await init();const title=required(data.title,120),channel=oneOf(data.channel,CHANNELS),body=required(data.body,3000),now=Date.now();
    if(id){const result=await execute('UPDATE support_templates SET title=?,channel=?,body=?,updated_at=? WHERE id=?',[title,channel,body,now,validInt(id,false)]);if(!pg&&!result.changes)fail('template_not_found',404);}
    else await execute('INSERT INTO support_templates(title,channel,body,created_by_id,created_at,updated_at) VALUES(?,?,?,?,?,?)',[title,channel,body,Number(actor.id),now,now]);return templates();}
  async function removeTemplate(id){await init();await execute('DELETE FROM support_templates WHERE id=?',[validInt(id,false)]);return templates();}
  async function overview(){await syncLegacy();
    const statuses=await execute('SELECT status,COUNT(*) AS n FROM support_tickets GROUP BY status');
    const reasons=await execute('SELECT reason,COUNT(*) AS n FROM support_tickets GROUP BY reason ORDER BY n DESC');
    const times=await execute('SELECT opened_at,first_response_at FROM support_tickets WHERE first_response_at IS NOT NULL');
    const averages=times.length?Math.round(times.reduce((s,r)=>s+Math.max(0,Number(r.first_response_at)-Number(r.opened_at)),0)/times.length/60000):null;
    const overdue=await execute("SELECT COUNT(*) AS n FROM support_tickets WHERE status<>'closed' AND last_customer_at>COALESCE(last_staff_at,0) AND last_customer_at+reminder_hours*3600000<=?",[Date.now()]);
    return {statuses:Object.fromEntries(STATUSES.map(s=>[s,Number(statuses.find(r=>r.status===s)?.n||0)])),reasons:reasons.map(r=>({reason:r.reason,count:Number(r.n)})),averageFirstResponseMinutes:averages,respondedTickets:times.length,overdue:Number(overdue[0]?.n||0)};
  }
  async function customerHistory(customerId){await syncLegacy();const id=validInt(customerId,false);
    const rows=await execute(`SELECT t.* FROM support_tickets t LEFT JOIN users u ON u.id=?
      WHERE t.customer_id=? OR (t.customer_id IS NULL AND u.email IS NOT NULL AND LOWER(t.customer_email)=LOWER(u.email))
      ORDER BY t.opened_at DESC,t.id DESC LIMIT 100`,[id,id]);return rows.map(ticketToJson);}
  async function reminders(){await init();const now=Date.now();const due=await execute(`SELECT t.id,t.subject,t.last_customer_at,t.customer_name,CASE WHEN u.is_blocked=0 THEN u.email ELSE NULL END AS staff_email,u.name AS staff_name
    FROM support_tickets t LEFT JOIN users u ON u.id=t.assignee_id
    WHERE t.status<>'closed' AND t.last_customer_at>COALESCE(t.last_staff_at,0)
    AND t.last_customer_at+t.reminder_hours*3600000<=? AND (t.reminded_for_at IS NULL OR t.reminded_for_at<t.last_customer_at)
    ORDER BY t.last_customer_at LIMIT 30`,[now]);
    if(!isEmailConfigured())return 0;
    let sent=0;
    for(const item of due){try{
      const email=item.staff_email||ownerEmail;if(!email)continue;
      await sendEmail({to:email,subject:'VerSans · פנייה #'+item.id+' ממתינה לתגובה',text:'הפנייה "'+item.subject+'" עדיין ממתינה לתגובה.\nלקוח: '+(item.customer_name||'-')+'\nפתח באדמין: /admin/support?ticket='+item.id});
      await execute('UPDATE support_tickets SET reminded_for_at=? WHERE id=? AND last_customer_at=? AND (reminded_for_at IS NULL OR reminded_for_at<?)',[Number(item.last_customer_at),item.id,Number(item.last_customer_at),Number(item.last_customer_at)]);sent++;
    }catch(error){console.error('Support reminder:',error.message);}}
    return sent;
  }
  return {init,syncLegacy,create,list,detail,update,message,replacement,templates,saveTemplate,removeTemplate,overview,customerHistory,reminders};
}
module.exports={createSupportCenter,STATUSES,REASONS,REPLACEMENT_STATES};
