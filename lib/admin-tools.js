  function dayStartInIsrael(day) {
    const utc=Date.parse(day+'T00:00:00Z');
    let guess=utc;
    for(let i=0;i<3;i++) {
      const p=Object.fromEntries(localParts.formatToParts(new Date(guess)).filter(x=>x.type!=='literal').map(x=>[x.type,Number(x.value)]));
      const rendered=Date.UTC(p.year,p.month-1,p.day,p.hour,p.minute,p.second);
      guess -= rendered-utc;
    }
    return guess;
  }
