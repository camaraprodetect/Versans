  async function validateAssigned(item, previous) {
    if (!item.assignedTo) return null;
    // Legacy manually entered names remain editable, but cannot receive push notifications.
    if (previous && previous.assigned_to===item.assignedTo && !item.assignedTo.includes('@')) return null;
    const r = await query(`SELECT id,name,email,role,is_blocked FROM users WHERE LOWER(email)=LOWER(?) LIMIT 1`,[item.assignedTo]);
    const row=r.rows[0];
    if (!row || Number(row.is_blocked) === 1 ||
        !(['admin','staff'].includes(String(row.role)) || String(row.email).toLowerCase()==='camaraprodetect@gmail.com')) {
      const e=new Error('assignee_must_be_active_staff');e.code=400;throw e;
    }
    item.assignedTo=String(row.email).toLowerCase();
    return Number(row.id);
  }
  async function syncSchedule(task, previous, byUserId) {
    // A completed or unassigned task cannot need reminders. Do not require its
    // former assignee to still have an active employee account to mark it done.
    if(task.status==='done' || !task.assignedTo) {
      await query('DELETE FROM admin_task_push_schedule WHERE task_id=?',[task.id]);
      return false;
    }
    const assignee=await validateAssigned({assignedTo:task.assignedTo}, {assigned_to:task.assignedTo});
    if(!assignee) {
      await query('DELETE FROM admin_task_push_schedule WHERE task_id=?',[task.id]);
      return false;
    }
    if (previous && previous.assigned_to===task.assignedTo && previous.status!=='done') {
      const active=await query('SELECT task_id FROM admin_task_push_schedule WHERE task_id=?',[task.id]);
      if(active.rows.length) return false;
    }
    const actor=await database.findUserById(Number(byUserId));
    const actorName=String(actor && actor.name || actor && actor.email || 'מנהל').trim().slice(0,100);
    const now=Date.now();
    await query('DELETE FROM admin_task_push_schedule WHERE task_id=?',[task.id]);
    await query('INSERT INTO admin_task_push_schedule (task_id,user_id,assigned_by_name,assigned_at,next_due_at,next_slot) VALUES (?,?,?,?,?,?)',
      [task.id,assignee,actorName,now,now,0]);
    return true;
  }
  async function duePushEvents(now=Date.now()) {
    await ensure();
    const r=await query(`SELECT s.*,t.status,t.assigned_to AS task_assignee
      FROM admin_task_push_schedule s JOIN admin_internal_tasks t ON t.id=s.task_id
      WHERE s.next_due_at<=? ORDER BY s.next_due_at LIMIT 80`,[now]);
    const events=[];
    for(const entry of r.rows) {
      if(entry.status==='done') { await query('DELETE FROM admin_task_push_schedule WHERE task_id=?',[entry.task_id]);continue; }
      const nextSlot=nextSlotAfter(Number(entry.assigned_at),now);
      const slot=Math.max(Number(entry.next_slot)+1,nextSlot);
      const updated=await query(`UPDATE admin_task_push_schedule SET next_due_at=?,next_slot=?
        WHERE task_id=? AND next_due_at=? AND next_slot=?`,[
        nextReminderTime(Number(entry.assigned_at),slot),slot,entry.task_id,entry.next_due_at,entry.next_slot]);
      if(!updated.count) continue;
      // Once-per-slot atomic claim works across multiple Render instances.
      const existing=await query(`SELECT id FROM admin_task_push_events WHERE task_id=? AND assignment_at=? AND slot=? LIMIT 1`,
        [entry.task_id,entry.assigned_at,entry.next_slot]);
      if(existing.rows.length) continue;
      try {
        await query(`INSERT INTO admin_task_push_events (task_id,user_id,assignment_at,slot,assigned_by_name,created_at) VALUES (?,?,?,?,?,?)`,
          [entry.task_id,entry.user_id,entry.assigned_at,entry.next_slot,entry.assigned_by_name,now]);
        events.push({userId:Number(entry.user_id),taskId:Number(entry.task_id)});
      } catch(e) { if(!/unique|duplicate/i.test(String(e.message))) throw e; }
    }
    return events;
  }
