const HOUR = 3600000;
// Reminder schedule: assignment, +6h, +12h, +24h, +36h, ...
function nextReminderTime(assignedAt, slot) {
  return assignedAt + (slot === 0 ? 0 : slot === 1 ? 6 : 12 + (slot - 2) * 12) * HOUR;
}
function nextSlotAfter(assignedAt, now) {
  if (now < assignedAt + 6 * HOUR) return 1;
  if (now < assignedAt + 12 * HOUR) return 2;
  return 3 + Math.floor((now - (assignedAt + 12 * HOUR)) / (12 * HOUR));
}


