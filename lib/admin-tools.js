    await ensure();const current=await getTask(id);if(!current)return null;
    const expected=Number(payload && payload.updatedAt);
    if (!Number.isSafeInteger(expected)||expected!==Number(current.updated_at)) { const err=new Error('task_changed');err.code=409;throw err; }
    // Status changes and task assignments submit only the fields that changed.
    // Merge with the current DB row so an omitted title/description is not erased
    // (or rejected as invalid), while a deliberately supplied empty value is still validated.
    const item=cleanTask({...publicTask(current), ...payload});
    if(item.assignedTo!==String(current.assigned_to||'')) await validateAssigned(item,current);
    const now=Math.max(Date.now(),expected+1);
    const completedAt=item.status==='done'?(current.status==='done'?current.completed_at||now:now):null;
    const args=[item.title,item.description,item.type,item.status,item.priority,item.assignedTo,item.dueDate,userId,now,completedAt,id,expected];
