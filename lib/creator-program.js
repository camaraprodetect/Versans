'use strict';

// Creator codes are reusable identifiers (optionally a discount). Revenue is
// counted from real paid orders only; historical codes remain attached to their
// owner even if that owner's current code changes.
const normalize = value => String(value || '').trim().toUpperCase().replace(/\s+/g, '').replace(/[^A-Z0-9-]/g, '').slice(0,40);

function createCreatorProgram(database) {
  const pg = database.backend === 'postgres';
  async function query(db, statement, values=[]) {
    if (pg) {
      let i = 0;
      const stmt = statement.replace(/\?/g, () => '$'+(++i));
      const result = await db._query(stmt, values);
      return { rows: result.rows || [], changed: Number(result.rowCount || 0) };
    }
    const stmt = db.db.prepare(statement);
    if (/^\s*SELECT\b/i.test(statement)) return { rows: stmt.all(...values), changed: 0 };
    const r = stmt.run(...values);
    return {rows: [], changed: Number(r.changes || 0)};
  }
  async function init() {
    const table = `CREATE TABLE IF NOT EXISTS creator_codes (
      code TEXT PRIMARY KEY,
      user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      discount_percent INTEGER NOT NULL DEFAULT 0 CHECK (discount_percent BETWEEN 0 AND 30),
      commission_percent INTEGER NOT NULL DEFAULT 0 CHECK (commission_percent BETWEEN 0 AND 100),
      active INTEGER NOT NULL DEFAULT 1 CHECK (active IN (0,1)),
      created_at BIGINT NOT NULL
    )`;
    if(pg) await database._query(table);
    else database.db.exec(table);
    // Existing installations created creator_codes without this column.
    if (pg) await database._query('ALTER TABLE creator_codes ADD COLUMN IF NOT EXISTS commission_percent INTEGER NOT NULL DEFAULT 0');
    else {
      const cols=database.db.prepare('PRAGMA table_info(creator_codes)').all();
      if (!cols.some(c=>c.name==='commission_percent')) database.db.exec('ALTER TABLE creator_codes ADD COLUMN commission_percent INTEGER NOT NULL DEFAULT 0');
    }
    const idx = `CREATE INDEX IF NOT EXISTS idx_creator_codes_owner ON creator_codes(user_id, active)`;
    if(pg) await database._query(idx); else database.db.exec(idx);
    // Rates are versioned at the time the admin changes them. A later edit must
    // never silently rewrite earnings on orders already paid.
    const history=`CREATE TABLE IF NOT EXISTS creator_commission_rates (
      id ${pg?'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY':'INTEGER PRIMARY KEY AUTOINCREMENT'},
      code TEXT NOT NULL REFERENCES creator_codes(code) ON DELETE CASCADE,
      commission_percent INTEGER NOT NULL CHECK (commission_percent BETWEEN 0 AND 100),
      effective_at BIGINT NOT NULL
    )`;
    if(pg) await database._query(history); else database.db.exec(history);
    const rateIdx='CREATE INDEX IF NOT EXISTS idx_creator_commission_rates_lookup ON creator_commission_rates(code,effective_at DESC,id DESC)';
    if(pg) await database._query(rateIdx); else database.db.exec(rateIdx);
    // Legacy creator sales belong to the creator, but earn zero retroactive
    // commission until a rate has actually been assigned.
    await query(database,`INSERT INTO creator_commission_rates(code,commission_percent,effective_at)
      SELECT c.code,0,c.created_at FROM creator_codes c
      WHERE NOT EXISTS(SELECT 1 FROM creator_commission_rates h WHERE h.code=c.code)`);
    const orderIdx='CREATE INDEX IF NOT EXISTS idx_creator_orders_paid ON orders(coupon_code,paid_at DESC,id DESC)';
    if(pg) await database._query(orderIdx); else database.db.exec(orderIdx);
  }
  async function getActiveCode(code) {
    const value=normalize(code);
    if(!value) return null;
    const result = await query(database, `SELECT c.code,c.user_id,c.discount_percent,u.name FROM creator_codes c JOIN users u ON u.id=c.user_id WHERE c.code=? AND c.active=1 AND u.role='contentcreator' AND u.is_blocked=0 LIMIT 1`,[value]);
    return result.rows[0] || null;
  }
  // The rate is resolved using the payment time, not the current rate.
  // ROUND is applied per paid order, so a commission total is the sum of
  // individually rounded earnings. No customer PII is returned to creators.
  const rateAtPayment=`COALESCE((SELECT h.commission_percent FROM creator_commission_rates h
    WHERE h.code=o.coupon_code AND h.effective_at<=o.paid_at
    ORDER BY h.effective_at DESC,h.id DESC LIMIT 1),0)`;
  const earnedExpression=`CAST(ROUND(o.amount_agorot * (${rateAtPayment}) / 100.0) AS INTEGER)`;
  async function listCreators() {
    const r = await query(database, `SELECT u.id,u.name,u.email,u.role,u.is_blocked,c.code,c.discount_percent,c.commission_percent,c.active,
      COUNT(o.id) AS sales,COALESCE(SUM(o.amount_agorot),0) AS revenue_agorot,
      COALESCE(SUM(${earnedExpression}),0) AS commission_agorot
      FROM users u JOIN creator_codes c ON c.user_id=u.id
      LEFT JOIN orders o ON o.coupon_code=c.code AND o.status='paid'
      GROUP BY u.id,u.name,u.email,u.role,u.is_blocked,c.code,c.discount_percent,c.commission_percent,c.active
      ORDER BY u.name ASC,c.created_at DESC`);
    const map = new Map();
    for (const row of r.rows) {
      let item=map.get(Number(row.id));
      if(!item){item={id:Number(row.id),name:row.name,email:row.email,role:row.role,blocked:Number(row.is_blocked)===1,code:'',discountPercent:0,commissionPercent:0,active:false,sales:0,revenueAgorot:0,commissionAgorot:0};map.set(item.id,item);}
      item.sales+=Number(row.sales||0);item.revenueAgorot+=Number(row.revenue_agorot||0);item.commissionAgorot+=Number(row.commission_agorot||0);
      if(Number(row.active)===1 && !item.code){item.code=row.code;item.discountPercent=Number(row.discount_percent||0);item.commissionPercent=Number(row.commission_percent||0);item.active=item.role==='contentcreator'&&!item.blocked;}
    }
    return [...map.values()];
  }
  async function getCreatorByUser(userId){
    const r=await query(database, `SELECT c.code,c.discount_percent,c.commission_percent,c.user_id,u.name,u.role,u.is_blocked FROM creator_codes c JOIN users u ON u.id=c.user_id WHERE c.user_id=? AND c.active=1 ORDER BY c.created_at DESC LIMIT 1`,[userId]);
    const row=r.rows[0];return row && row.role==='contentcreator'&&Number(row.is_blocked)===0?row:null;
  }
  async function grantByEmail(email,code,percent,commissionPercent){
    const normalizedEmail=String(email||'').trim().toLowerCase();
    const normalizedCode=normalize(code);
    const rate=Number(percent);
    if(!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(normalizedEmail)) throw Object.assign(new Error('invalid_email'),{status:400});
    if(!/^[A-Z0-9][A-Z0-9-]{3,19}$/.test(normalizedCode)) throw Object.assign(new Error('invalid_creator_code'),{status:400});
    if(!Number.isInteger(rate)||rate<0||rate>30) throw Object.assign(new Error('invalid_discount_percent'),{status:400});
    return database.transaction(async tx=>{
      const user=(await query(tx,'SELECT id,name,email,role,is_blocked FROM users WHERE LOWER(email)=? LIMIT 1',[normalizedEmail])).rows[0];
      if(!user) throw Object.assign(new Error('user_not_found'),{status:404});
      if(Number(user.is_blocked)===1) throw Object.assign(new Error('blocked_user'),{status:400});
      if(['admin','staff'].includes(user.role)) throw Object.assign(new Error('protected_role'),{status:403});
      const current=(await query(tx,'SELECT commission_percent FROM creator_codes WHERE user_id=? AND active=1 ORDER BY created_at DESC LIMIT 1',[user.id])).rows[0];
      // Older admin clients may omit commissionPercent. Keep the saved value.
      const earningsRate=(commissionPercent===undefined||commissionPercent===null||commissionPercent==='')
        ? Number(current?.commission_percent || 0) : Number(commissionPercent);
      if(!Number.isInteger(earningsRate)||earningsRate<0||earningsRate>100) throw Object.assign(new Error('invalid_commission_percent'),{status:400});
      const existing=(await query(tx,'SELECT code,user_id,commission_percent FROM creator_codes WHERE code=? LIMIT 1',[normalizedCode])).rows[0];
      if(existing && Number(existing.user_id)!==Number(user.id)) throw Object.assign(new Error('creator_code_taken'),{status:409});
      const welcome=(await query(tx,'SELECT code FROM coupons WHERE code=? LIMIT 1',[normalizedCode])).rows[0];
      if(welcome) throw Object.assign(new Error('coupon_code_taken'),{status:409});
      // Preserve old inactive codes for accurate lifetime history.
      await query(tx,'UPDATE creator_codes SET active=0 WHERE user_id=?',[user.id]);
      if(existing) await query(tx,'UPDATE creator_codes SET active=1,discount_percent=?,commission_percent=? WHERE code=?',[rate,earningsRate,normalizedCode]);
      else await query(tx,'INSERT INTO creator_codes(code,user_id,discount_percent,commission_percent,active,created_at) VALUES(?,?,?,?,1,?)',[normalizedCode,user.id,rate,earningsRate,Date.now()]);
      // Write a new rate only if it differs from the last historical rate.
      const latest=(await query(tx,'SELECT commission_percent FROM creator_commission_rates WHERE code=? ORDER BY effective_at DESC,id DESC LIMIT 1',[normalizedCode])).rows[0];
      if(!latest || Number(latest.commission_percent)!==earningsRate){
        await query(tx,'INSERT INTO creator_commission_rates(code,commission_percent,effective_at) VALUES(?,?,?)',[normalizedCode,earningsRate,Date.now()]);
      }
      await query(tx,"UPDATE users SET role='contentcreator' WHERE id=?",[user.id]);
      return {id:Number(user.id),name:user.name,code:normalizedCode,discountPercent:rate,commissionPercent:earningsRate};
    });
  }
  async function revoke(userId){
    const id=Number(userId);
    return database.transaction(async tx=>{
      const r=await query(tx,"UPDATE users SET role='customer' WHERE id=? AND role='contentcreator'",[id]);
      await query(tx,'UPDATE creator_codes SET active=0 WHERE user_id=?',[id]);
      return r.changed>0;
    });
  }
  // Report time ranges are shared by the private dashboard and the public-to-creators
  // leaderboard. Never accept arbitrary SQL or a date from the browser.
  const RANGES = Object.freeze(['all','year','6months','3months','month','week','3days','today']);
  const JERUSALEM = 'Asia/Jerusalem';
  const localParts = (stamp) => {
    const parts = new Intl.DateTimeFormat('en-GB', {
      timeZone:JERUSALEM, year:'numeric',month:'2-digit',day:'2-digit',
      hour:'2-digit',minute:'2-digit',second:'2-digit',hourCycle:'h23'
    }).formatToParts(new Date(stamp));
    const result={};
    for (const part of parts) if (part.type!=='literal') result[part.type]=Number(part.value);
    return result;
  };
  const offsetAt = (stamp) => {
    const p=localParts(stamp);
    return Date.UTC(p.year,p.month-1,p.day,p.hour,p.minute,p.second)-Math.floor(stamp/1000)*1000;
  };
  const jerusalemMidnight = (year,month,day) => {
    const localUtc = Date.UTC(year,month-1,day);
    let guess=localUtc-offsetAt(localUtc);
    guess=localUtc-offsetAt(guess);
    return guess;
  };
  function reportPeriod(range='all', now=Date.now()) {
    if (!RANGES.includes(range)) return null;
    if (range==='all') return {range,since:null};
    if (range==='today') {
      const p=localParts(now);
      return {range,since:jerusalemMidnight(p.year,p.month,p.day)};
    }
    if (range==='week') return {range,since:now-7*86400000};
    if (range==='3days') return {range,since:now-3*86400000};
    const months={year:12,'6months':6,'3months':3,month:1}[range];
    if (months) {
      // Genuine calendar months (not approximated 30/90/180 days).
      const cutoff=new Date(now);
      const originalDay=cutoff.getUTCDate();
      cutoff.setUTCDate(1);
      cutoff.setUTCMonth(cutoff.getUTCMonth()-months);
      const lastDayOfMonth=new Date(Date.UTC(cutoff.getUTCFullYear(),cutoff.getUTCMonth()+1,0)).getUTCDate();
      cutoff.setUTCDate(Math.min(originalDay,lastDayOfMonth));
      return {range,since:cutoff.getTime()};
    }
    return null;
  }
  async function dashboard(userId,range='all'){
    const creator=await getCreatorByUser(userId);
    if(!creator) return null;
    const period=reportPeriod(range);
    if(!period) return null;
    const conditions=period.since===null ? '' : ' AND o.paid_at>=?';
    const values=period.since===null ? [userId] : [period.since,userId];
    const r=await query(database,`SELECT COUNT(o.id) AS sales,
      COALESCE(SUM(o.amount_agorot),0) AS revenue_agorot,
      COALESCE(SUM(${earnedExpression}),0) AS commission_agorot,
      MAX(o.paid_at) AS last_paid_at
      FROM creator_codes c
      LEFT JOIN orders o ON o.coupon_code=c.code AND o.status='paid'${conditions}
      WHERE c.user_id=?`,values);
    const a=r.rows[0]||{};
    return {
      name:creator.name,code:creator.code,
      discountPercent:Number(creator.discount_percent||0),
      commissionPercent:Number(creator.commission_percent||0),
      range:period.range,sales:Number(a.sales||0),
      revenueAgorot:Number(a.revenue_agorot||0),
      commissionAgorot:Number(a.commission_agorot||0),
      lastPaidAt:a.last_paid_at ? Number(a.last_paid_at) : null
    };
  }
  async function purchases(userId,range='all',cursor='',requestedLimit=15){
    const creator=await getCreatorByUser(userId);
    if(!creator) return null;
    const period=reportPeriod(range);
    if(!period) return null;
    const limit=Number(requestedLimit);
    if(!Number.isInteger(limit)||limit<1||limit>30) return null;
    const values=[userId];
    let clause='';
    if(period.since!==null){clause+=' AND o.paid_at>=?';values.push(period.since);}
    const cursorValue=String(cursor||'');
    if(cursorValue){
      const parsed=/^([1-9]\d{11,14})\.([1-9]\d{0,17})$/.exec(cursorValue);
      if(!parsed) return null;
      const paidAt=Number(parsed[1]),id=Number(parsed[2]);
      if(!Number.isSafeInteger(paidAt)||!Number.isSafeInteger(id)) return null;
      clause+=' AND (o.paid_at<? OR (o.paid_at=? AND o.id<?))';
      values.push(paidAt,paidAt,id);
    }
    values.push(limit+1);
    const r=await query(database,`SELECT o.id,o.order_ref,o.paid_at,o.amount_agorot,o.coupon_code,
      ${rateAtPayment} AS applied_percent,${earnedExpression} AS commission_agorot
      FROM orders o JOIN creator_codes c ON c.code=o.coupon_code
      WHERE c.user_id=? AND o.status='paid'${clause}
      ORDER BY o.paid_at DESC,o.id DESC LIMIT ?`,values);
    const hasMore=r.rows.length>limit;
    const page=r.rows.slice(0,limit);
    return {range,hasMore,nextCursor:hasMore&&page.length?`${Number(page[page.length-1].paid_at)}.${Number(page[page.length-1].id)}`:null,
      orders:page.map(o=>({orderRef:o.order_ref,paidAt:Number(o.paid_at),amountAgorot:Number(o.amount_agorot),
        code:o.coupon_code,commissionPercent:Number(o.applied_percent||0),commissionAgorot:Number(o.commission_agorot||0)}))};
  }
  async function leaderboard(range='all'){
    const period=reportPeriod(range);
    if(!period) return null;
    const conditions=period.since===null ? '' : ' AND o.paid_at>=?';
    const values=period.since===null ? [] : [period.since];
    const r=await query(database,`SELECT u.id,u.name,COUNT(o.id) AS sales
      FROM users u JOIN creator_codes c ON c.user_id=u.id
      LEFT JOIN orders o ON o.coupon_code=c.code AND o.status='paid'${conditions}
      WHERE u.role='contentcreator' AND u.is_blocked=0
      GROUP BY u.id,u.name ORDER BY sales DESC,u.name ASC`,values);
    const entries=[];
    for(const row of r.rows){
      const active=await getCreatorByUser(row.id);
      if(active) entries.push({name:row.name,code:active.code,sales:Number(row.sales||0)});
    }
    return entries;
  }
  return {init,getActiveCode,grantByEmail,revoke,listCreators,dashboard,purchases,leaderboard,getCreatorByUser,normalize,reportPeriod};
}
module.exports={createCreatorProgram};
