  async adminTrafficSummary(since = null) {
    const scalar = await this._query('SELECT COUNT(*)::int AS count FROM visitor_page_views WHERE ($1::bigint IS NULL OR viewed_at>=$1)', [since]);
    const grouped = async (field, table = 'visitor_page_views', timestampField = 'viewed_at', extraWhere = '') => {
      const r = await this._query(`SELECT ${field} AS label,COUNT(*)::int AS count FROM ${table} WHERE ($1::bigint IS NULL OR ${timestampField}>=$1) ${extraWhere} GROUP BY ${field} ORDER BY count DESC,label ASC LIMIT 12`, [since]);
      return r.rows.map((row) => ({ label: row.label || '(ישיר / לא ידוע)', count: Number(row.count || 0) }));
    };
    const [topPages, entryPages, referrers, utmSources, devices, browsers, operatingSystems] = await Promise.all([
      grouped('path'), grouped('entry_path','visitor_presence','first_seen'),
      grouped('referrer','visitor_page_views','viewed_at',"AND referrer IS NOT NULL AND referrer<>''"),
      grouped('utm_source','visitor_page_views','viewed_at',"AND utm_source IS NOT NULL AND utm_source<>''"),
      grouped('device_type','visitor_presence','last_seen'), grouped('browser','visitor_presence','last_seen'), grouped('os','visitor_presence','last_seen')
    ]);
    return { pageViews: Number(scalar.rows[0] ? scalar.rows[0].count : 0), topPages, entryPages, referrers, utmSources, devices, browsers, operatingSystems };
  }

