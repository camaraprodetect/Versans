function createDatabase(options = {}) {
  const databaseUrl = options.databaseUrl !== undefined ? options.databaseUrl : (process.env.DATABASE_URL || '');
  if (databaseUrl) return new PostgresStore(databaseUrl, options.pgPool);
  const sqlitePath = options.sqlitePath || process.env.VERSANS_DB_PATH || path.join(options.root || process.cwd(), 'data', 'versans.sqlite');
  return new SqliteStore(path.resolve(sqlitePath));
}

