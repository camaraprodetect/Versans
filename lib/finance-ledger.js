'use strict';
// Administration-only bookkeeping. Refund records never charge/refund a card:
// real HYP settlements must be checked in the payment processor separately.
const CATEGORIES = Object.freeze(['מוצרים ומלאי','פרסום ושיווק','אריזות','משלוחים','עמלות סליקה','יוצרי תוכן','ציוד','שכר','תוכנה ושירותים','שירותים','אחר']);
const datePattern = /^\d{4}-\d{2}-\d{2}$/;
const validDate = date => datePattern.test(date) && !Number.isNaN(Date.parse(date+'T00:00:00Z')) && new Date(date+'T00:00:00Z').toISOString().slice(0,10)===date;
const todayIsrael = (now=Date.now()) => new Intl.DateTimeFormat('en-CA',{timeZone:'Asia/Jerusalem',year:'numeric',month:'2-digit',day:'2-digit'}).format(new Date(now));
const fail = (msg,status=400) => Object.assign(new Error(msg),{status});
function israelMidnight(date){
  const utc=Date.parse(date+'T00:00:00Z');
  let instant=utc-3*3600000;
  const f=new Intl.DateTimeFormat('en-US',{timeZone:'Asia/Jerusalem',timeZoneName:'shortOffset'});
  for(let i=0;i<3;i++){
    const v=f.formatToParts(new Date(instant)).find(p=>p.type==='timeZoneName').value;
    const m=/GMT([+-])(\d{1,2})(?::(\d{2}))?/.exec(v);
    if(!m)throw fail('timezone_error',500);
    const minutes=(Number(m[2])*60+Number(m[3]||0))*(m[1]==='+'?1:-1);
    instant=utc-minutes*60000;
  }
  return instant;
}
function nextDay(date){return new Date(Date.parse(date+'T00:00:00Z')+86400000).toISOString().slice(0,10);}
function agorot(text,allowZero=false) {
  const value=String(text??'');
  if(!/^\d{1,8}(?:\.\d{1,2})?$/.test(value))throw fail('invalid_amount');
  const n=Math.round(Number(value)*100);
  if(!Number.isSafeInteger(n)||n<(allowZero?0:1))throw fail('invalid_amount');
  return n;
}
function validateExpense(body) {
  const description=String(body.description||'').trim(),category=String(body.category||'אחר').trim();
  const expenseDate=String(body.date||'').trim();
  if(!description||description.length>300||!category||category.length>70||!validDate(expenseDate))throw fail('invalid_expense');
  const hasSplit=body.maorAmount!=null||body.galAmount!=null;
  const maorAgorot=hasSplit?agorot(body.maorAmount??'0',true):null;
  const galAgorot=hasSplit?agorot(body.galAmount??'0',true):null;
  const amountAgorot=agorot(body.amount);
  if(hasSplit&&maorAgorot+galAgorot!==amountAgorot)throw fail('invalid_split');
  return {description,category,expenseDate,amountAgorot,maorAgorot,galAgorot};
}
function money(ag){return (Number(ag||0)/100).toFixed(2);}
function csvCell(value){
  let s=String(value==null?'':value);
  if(/^[\s\u200b]*[=+\-@]/u.test(s))s="'"+s; // Excel injection defense
  return '"'+s.replace(/"/g,'""')+'"';
}
function monthDate(month,day){
  const [y,m]=month.split('-').map(Number),max=new Date(Date.UTC(y,m,0)).getUTCDate();
  return month+'-'+String(Math.min(day,max)).padStart(2,'0');
}
function nextMonth(key){const [y,m]=key.split('-').map(Number);return m===12?`${y+1}-01`:`${y}-${String(m+1).padStart(2,'0')}`;}
function createFinanceLedger(database){
  const pg=database.backend==='postgres';
  let ready;
  async function query(sql,args=[],tx=database){
    if(pg){let k=0;return (await tx._query(sql.replace(/\?/g,()=>'$'+(++k)),args)).rows||[];}
    const statement=tx.db.prepare(sql);
    return /^\s*(?:SELECT|WITH)\b/i.test(sql)||/\bRETURNING\b/i.test(sql)?statement.all(...args):(statement.run(...args),[]);
  }
  function init(){if(!ready)ready=(async()=>{
    const id=pg?'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY':'INTEGER PRIMARY KEY AUTOINCREMENT';
    for(const sql of [
      `CREATE TABLE IF NOT EXISTS admin_expense_audit (id ${id},expense_id BIGINT NOT NULL,action TEXT NOT NULL,old_json TEXT,new_json TEXT,reason TEXT NOT NULL DEFAULT '',actor_id INTEGER,actor_name TEXT NOT NULL,created_at BIGINT NOT NULL)`,
      `CREATE INDEX IF NOT EXISTS idx_finance_audit_expense ON admin_expense_audit(expense_id,created_at DESC)`,
      `CREATE TABLE IF NOT EXISTS admin_recurring_expenses (id ${id},description TEXT NOT NULL,category TEXT NOT NULL,amount_agorot BIGINT NOT NULL,maor_agorot BIGINT,gal_agorot BIGINT,start_date TEXT NOT NULL,day_of_month INTEGER NOT NULL,active INTEGER NOT NULL DEFAULT 1,resume_date TEXT NOT NULL DEFAULT '',created_by INTEGER,created_name TEXT NOT NULL,created_at BIGINT NOT NULL)`,
      `CREATE TABLE IF NOT EXISTS admin_order_refunds (id ${id},order_ref TEXT NOT NULL,amount_agorot BIGINT NOT NULL,provider_reference TEXT NOT NULL DEFAULT '',status TEXT NOT NULL DEFAULT 'pending',note TEXT NOT NULL DEFAULT '',actor_id INTEGER,actor_name TEXT NOT NULL,created_at BIGINT NOT NULL,confirmed_at BIGINT,confirmed_by TEXT,cancelled_at BIGINT,cancel_reason TEXT,request_id TEXT NOT NULL UNIQUE)`,
      `CREATE INDEX IF NOT EXISTS idx_finance_refunds_order ON admin_order_refunds(order_ref,created_at DESC)`,
      `CREATE UNIQUE INDEX IF NOT EXISTS uq_finance_refund_provider ON admin_order_refunds(order_ref,provider_reference) WHERE provider_reference<>'' AND cancelled_at IS NULL`,
      `CREATE TABLE IF NOT EXISTS admin_refund_audit (id ${id},refund_id BIGINT NOT NULL,action TEXT NOT NULL,actor_name TEXT NOT NULL,reason TEXT NOT NULL DEFAULT '',created_at BIGINT NOT NULL)`
    ])await query(sql);
  })().catch(e=>{ready=null;throw e;});return ready;}
  const actorName=a=>String(a.name||a.email||'אדמין').slice(0,150);
  async function auditExpense(tx,expenseId,action,old,newValue,reason,actor){
    await query(`INSERT INTO admin_expense_audit(expense_id,action,old_json,new_json,reason,actor_id,actor_name,created_at) VALUES(?,?,?,?,?,?,?,?)`,
      [expenseId,action,old?JSON.stringify(old):null,newValue?JSON.stringify(newValue):null,reason||'',actor.id,actorName(actor),Date.now()],tx);
  }
  async function modifyExpense(id,action,body,actor){
    await init();
    if(!Number.isSafeInteger(id)||id<=0||!['edit','cancel'].includes(action))throw fail('invalid_request');
    return database.transaction(async tx=>{
      const rows=await query('SELECT * FROM admin_expenses WHERE id=?'+(pg?' FOR UPDATE':''),[id],tx);
      const old=rows[0];
      if(!old)throw fail('expense_not_found',404);
      if(old.cancelled_at!=null)throw fail('expense_already_cancelled',409);
      // A creator payout must remain linked to the creator ledger; editing it would corrupt liabilities.
      const payouts=await query('SELECT id FROM admin_creator_payments WHERE request_id=? LIMIT 1',[old.request_id],tx);
      if(payouts.length)throw fail('creator_payout_locked',409);
      const at=Date.now(),name=actorName(actor);
      if(action==='edit'){
        const value=validateExpense(body);
        await query(`UPDATE admin_expenses SET description=?,category=?,amount_agorot=?,maor_agorot=?,gal_agorot=?,expense_date=?,modified_at=?,modified_by=? WHERE id=?`,
          [value.description,value.category,value.amountAgorot,value.maorAgorot,value.galAgorot,value.expenseDate,at,name,id],tx);
        await auditExpense(tx,id,'edit',old,value,'',actor);
      }else{
        const reason=String(body.reason||'').trim();
        if(reason.length<3||reason.length>300)throw fail('cancel_reason_required');
        await query('UPDATE admin_expenses SET cancelled_at=?,cancel_reason=?,modified_at=?,modified_by=? WHERE id=?',[at,reason,at,name,id],tx);
        await auditExpense(tx,id,'cancel',old,{cancelledAt:at},reason,actor);
      }
      return {id,action};
    });
  }
  async function expenseHistory(id){await init();return query('SELECT action,old_json,new_json,reason,actor_name,created_at FROM admin_expense_audit WHERE expense_id=? ORDER BY created_at DESC,id DESC',[id]);}
  async function categorySummary(from='',to=''){
    await init();
    return query(`SELECT category,COUNT(*) AS count,COALESCE(SUM(amount_agorot),0) AS amount_agorot FROM admin_expenses WHERE cancelled_at IS NULL AND (?='' OR expense_date>=?) AND (?='' OR expense_date<=?) GROUP BY category ORDER BY amount_agorot DESC`,[from,from,to,to]);
  }
  async function createRecurring(body,actor){
    await init();const item=validateExpense(body);
    if(item.expenseDate<'2020-01-01')throw fail('invalid_date');
    const day=Number(body.dayOfMonth||Number(item.expenseDate.slice(8)));
    if(!Number.isInteger(day)||day<1||day>31)throw fail('invalid_month_day');
    const rows=await query(`INSERT INTO admin_recurring_expenses(description,category,amount_agorot,maor_agorot,gal_agorot,start_date,day_of_month,active,created_by,created_name,created_at) VALUES(?,?,?,?,?,?,?,1,?,?,?) RETURNING id`,
      [item.description,item.category,item.amountAgorot,item.maorAgorot,item.galAgorot,item.expenseDate,day,actor.id,actorName(actor),Date.now()]);
    return Number(rows[0].id);
  }
  async function recurringList(){await init();return query('SELECT * FROM admin_recurring_expenses ORDER BY active DESC,id DESC');}
  async function setRecurringActive(id,active){
    await init();const result=await query('SELECT id FROM admin_recurring_expenses WHERE id=?',[id]);if(!result.length)throw fail('recurring_not_found',404);
    await query('UPDATE admin_recurring_expenses SET active=?,resume_date=CASE WHEN ?=1 AND active=0 THEN ? ELSE resume_date END WHERE id=?',[active?1:0,active?1:0,todayIsrael(),id]);return true;
  }
  async function generateRecurring(asOf=todayIsrael()){
    await init();if(!validDate(asOf))throw fail('invalid_date');
    let generated=0;
    await database.transaction(async tx=>{
      const rules=await query('SELECT * FROM admin_recurring_expenses WHERE active=1'+(pg?' FOR UPDATE':''),[],tx);
      for(const r of rules){
        let m=String(r.start_date).slice(0,7),count=0;
        while(m<=asOf.slice(0,7)&&count++<240){
          const date=monthDate(m,Number(r.day_of_month));
          if(date>=r.start_date&&(!r.resume_date||date>=r.resume_date)&&date<=asOf){
            const key=`recurring:${r.id}:${m}`;
            const existing=await query('SELECT id FROM admin_expenses WHERE request_id=?',[key],tx);
            if(!existing.length){
              await tx.createAdminExpense({description:r.description,category:r.category,amountAgorot:Number(r.amount_agorot),maorAgorot:r.maor_agorot==null?null:Number(r.maor_agorot),galAgorot:r.gal_agorot==null?null:Number(r.gal_agorot),expenseDate:date,employeeUserId:null,employeeName:'הוצאה חודשית אוטומטית: '+r.created_name,requestId:key,createdAt:Date.now()});
              generated++;
            }
          }
          m=nextMonth(m);
        }
      }
    });return generated;
  }
  async function createRefund(body,actor){
    await init();
    const orderRef=String(body.orderRef||'').trim(),providerReference=String(body.providerReference||'').trim(),note=String(body.note||'').trim(),key=String(body.requestId||'');
    if(!orderRef||orderRef.length>90||providerReference.length>140||note.length>400||!/^[-a-f0-9]{36}$/i.test(key))throw fail('invalid_refund');
    const amount=agorot(body.amount);
    return database.transaction(async tx=>{
      const duplicate=await query('SELECT id,order_ref,amount_agorot FROM admin_order_refunds WHERE request_id=?',[key],tx);
      if(duplicate.length){if(duplicate[0].order_ref!==orderRef||Number(duplicate[0].amount_agorot)!==amount)throw fail('request_conflict',409);return Number(duplicate[0].id);}
      const orders=await query("SELECT order_ref,amount_agorot FROM orders WHERE order_ref=? AND status='paid' AND order_ref NOT LIKE 'VS-DEMO-%'"+(pg?' FOR UPDATE':''),[orderRef],tx);
      if(!orders.length)throw fail('paid_order_not_found',404);
      const prior=await query('SELECT COALESCE(SUM(amount_agorot),0) AS reserved FROM admin_order_refunds WHERE order_ref=? AND cancelled_at IS NULL',[orderRef],tx);
      if(Number(prior[0].reserved)+amount>Number(orders[0].amount_agorot))throw fail('refund_exceeds_paid_amount',409);
      const inserted=await query(`INSERT INTO admin_order_refunds(order_ref,amount_agorot,provider_reference,status,note,actor_id,actor_name,created_at,request_id) VALUES(?,?,?,'pending',?,?,?,?,?) RETURNING id`,
        [orderRef,amount,providerReference,note,actor.id,actorName(actor),Date.now(),key],tx);
      return Number(inserted[0].id);
    });
  }
  async function updateRefund(id,action,body,actor){
    await init();return database.transaction(async tx=>{
      const rows=await query('SELECT * FROM admin_order_refunds WHERE id=?'+(pg?' FOR UPDATE':''),[id],tx);const row=rows[0];
      if(!row)throw fail('refund_not_found',404);
      if(row.cancelled_at!=null)throw fail('refund_cancelled',409);
      if(action==='confirm'){
        const reference=String(body.providerReference||row.provider_reference||'').trim();
        if(!reference||reference.length>140)throw fail('provider_reference_required');
        if(row.status!=='pending')throw fail('already_confirmed',409);
        await query("UPDATE admin_order_refunds SET status='confirmed',confirmed_at=?,confirmed_by=?,provider_reference=? WHERE id=?",[Date.now(),actorName(actor),reference,id],tx);
      }else if(action==='cancel'){
        const reason=String(body.reason||'').trim();if(reason.length<3||reason.length>300)throw fail('cancel_reason_required');
        await query('UPDATE admin_order_refunds SET cancelled_at=?,cancel_reason=? WHERE id=?',[Date.now(),reason,id],tx);
      }else throw fail('invalid_action');
      await query('INSERT INTO admin_refund_audit(refund_id,action,actor_name,reason,created_at) VALUES(?,?,?,?,?)',[id,action,actorName(actor),String(body.reason||'').slice(0,300),Date.now()],tx);
      return true;
    });
  }
  async function refundList({from='',to='',limit=50,offset=0}={}){
    await init();
    const effectiveTime="CASE WHEN status='confirmed' THEN COALESCE(confirmed_at,created_at) ELSE created_at END";
    const where=`WHERE (CAST(? AS BIGINT) IS NULL OR ${effectiveTime}>=?) AND (CAST(? AS BIGINT) IS NULL OR ${effectiveTime}<?)`;
    const since=from?israelMidnight(from):null,until=to?israelMidnight(nextDay(to)):null;
    const args=[since,since,until,until];
    const summary=(await query(`SELECT COUNT(*) AS count,COALESCE(SUM(CASE WHEN status='confirmed' AND cancelled_at IS NULL THEN 1 ELSE 0 END),0) AS confirmed_count,COALESCE(SUM(CASE WHEN status='confirmed' AND cancelled_at IS NULL THEN amount_agorot ELSE 0 END),0) AS confirmed,COALESCE(SUM(CASE WHEN status='pending' AND cancelled_at IS NULL THEN amount_agorot ELSE 0 END),0) AS pending FROM admin_order_refunds ${where}`,args))[0];
    const rows=await query(`SELECT * FROM admin_order_refunds ${where} ORDER BY created_at DESC,id DESC LIMIT ? OFFSET ?`,args.concat([limit,offset]));
    return {rows,total:Number(summary.count),confirmedCount:Number(summary.confirmed_count),confirmedAgorot:Number(summary.confirmed),pendingAgorot:Number(summary.pending)};
  }
  async function exportCsv(kind,from='',to=''){
    await init();if(!['expenses','income','refunds','combined'].includes(kind))throw fail('invalid_export');
    const dates=[];
    if(kind==='expenses'||kind==='combined'){
      for(let offset=0;;offset+=500){const r=await database.listAdminExpenses({from,to,limit:500,offset});dates.push(...r.rows.map(x=>({date:x.expense_date,type:x.cancelled_at?'הוצאה מבוטלת':'הוצאה',description:x.description,category:x.category,order:'',gross:'',refund:'',expense:x.cancelled_at?'0.00':money(x.amount_agorot),originalExpense:money(x.amount_agorot),maor:x.cancelled_at?'0.00':x.maor_agorot==null?'':money(x.maor_agorot),gal:x.cancelled_at?'0.00':x.gal_agorot==null?'':money(x.gal_agorot),employee:x.employee_name,reference:x.request_id,status:x.cancelled_at?'בוטל: '+x.cancel_reason:'פעיל'})));if(offset+500>=r.total)break;if(offset>=25000)throw fail('export_too_large',413);}
    }
    if(kind==='income'||kind==='combined'){
      // Money is attributed to original paid date; refunds appear as separate negative income rows.
      for(let offset=0;;offset+=500){const r=await database.listAdminIncome({since:from?israelMidnight(from):null,before:to?israelMidnight(nextDay(to)):null,limit:500,offset});
        const rows=r.rows.filter(x=>{const d=todayIsrael(Number(x.paid_at));return (!from||d>=from)&&(!to||d<=to);});
        dates.push(...rows.map(x=>({date:todayIsrael(Number(x.paid_at)),type:'הכנסה',description:'הזמנה ששולמה',category:'מכירות',order:x.order_ref,gross:money(x.amount_agorot),refund:'',expense:'',originalExpense:'',maor:'',gal:'',employee:'',reference:'',status:'שולם'})));
        if(offset+500>=r.total)break;if(offset>=25000)throw fail('export_too_large',413);
      }
    }
    if(kind==='refunds'||kind==='combined'||kind==='income'){
      for(let offset=0;;offset+=500){const r=await refundList({from,to,limit:500,offset});
        dates.push(...r.rows.map(x=>({date:todayIsrael(Number(x.status==='confirmed'&&x.confirmed_at?x.confirmed_at:x.created_at)),type:x.cancelled_at?'החזר מבוטל':'החזר',description:x.note||'החזר הזמנה',category:'זיכויים והחזרים',order:x.order_ref,gross:'',refund:x.status==='confirmed'&&!x.cancelled_at?money(x.amount_agorot):'0.00',expense:'',originalExpense:'',maor:'',gal:'',employee:x.actor_name,reference:x.provider_reference,status:x.cancelled_at?'בוטל: '+(x.cancel_reason||''):x.status==='confirmed'?'אומת ידנית':'ממתין לאימות'})));
        if(offset+500>=r.total)break;if(offset>=25000)throw fail('export_too_large',413);
      }
    }
    dates.sort((a,b)=>b.date.localeCompare(a.date));
    const headers=['תאריך','סוג','תיאור','קטגוריה','מספר הזמנה','הכנסה ברוטו (₪)','החזר מאומת (₪)','הוצאה בספרים (₪)','סכום הוצאה מקורי (₪)','מאור (₪)','גל (₪)','עובד מדווח','אסמכתה','סטטוס'];
    const keys=['date','type','description','category','order','gross','refund','expense','originalExpense','maor','gal','employee','reference','status'];
    return '\uFEFF'+[headers.map(csvCell).join(','),...dates.map(row=>keys.map(key=>csvCell(row[key])).join(','))].join('\r\n')+'\r\n';
  }
  return {init,modifyExpense,expenseHistory,categorySummary,createRecurring,recurringList,setRecurringActive,generateRecurring,createRefund,updateRefund,refundList,exportCsv,CATEGORIES};
}
module.exports={createFinanceLedger,validateExpense,agorot,CATEGORIES,todayIsrael};
